#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum V2Form {
    Binary,
    Control,
    Control64,
    Blend,
    Memory,
    Extract,
    Insert,
    Crc32,
    Fisttp,
    Cx16,
    Nullary,
}
#[derive(Clone, Copy, Debug)]
pub struct V2Spec {
    pub mnemonic: &'static str,
    pub family: &'static str,
    pub prefix: u8,
    /// 0x0f = two-byte map; 0x38/0x3a = three-byte maps.
    pub map: u8,
    pub byte: u8,
    /// Zero for variable-width and nullary forms; see V2Form.
    pub memory_bits: u16,
    pub form: V2Form,
}

#!/usr/bin/env python3
"""Generate one named Clang-oracle case per pinned M5 numeric encoding form."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def case(record):
    name = record['name']
    op, cls, *tags = name.split('_')
    op = op.lower()
    tag = '_'.join(tags)
    fields = {f['name'] for f in record['encoding']['values'] if 'x' in f['value']['value']}
    scalar = cls.startswith('asisd')
    if 'fp16' in cls:
        d, n, m = ('h0', 'h1', 'h2') if scalar else ('v0.8h', 'v1.8h', 'v2.8h')
        return f'{op} {d}, {n}' + (', #0.0' if tag == 'FZ' else f', {m}' if 'Rm' in fields else '')
    if cls == 'asisdpair':
        return f'{op} h0, v1.2h'
    if cls == 'asimdall':
        return f'{op} h0, v1.8h'
    if cls == 'asimdimm':
        return 'fmov v0.8h, #1.0'
    if cls in ('asimdelem', 'asisdelem') and tag == 'RH_H':
        return f'{op} ' + ('h0, h1' if scalar else 'v0.8h, v1.8h') + ', v2.h[1]'
    if cls in ('asimdelem', 'asisdelem') and op in ('sqrdmlah', 'sqrdmlsh'):
        return f'{op} ' + ('h0, h1' if scalar else 'v0.8h, v1.8h') + ', v2.h[1]'
    if cls in ('asimdsame2', 'asisdsame2') and op in ('sqrdmlah', 'sqrdmlsh'):
        return f'{op} ' + ('h0, h1, h2' if scalar else 'v0.8h, v1.8h, v2.8h')
    if cls == 'advsimd':
        return 'fcmla v0.4s, v1.4s, v2.s[1], #90'
    if op in ('fcmla', 'fcadd'):
        return f'{op} v0.4s, v1.4s, v2.4s, #90'
    if op in ('fmlal', 'fmlsl', 'fmlal2', 'fmlsl2'):
        return f'{op} v0.4s, v1.4h, ' + ('v2.h[1]' if cls == 'asimdelem' else 'v2.4h')
    if op in ('sdot', 'udot', 'usdot', 'sudot', 'bfdot'):
        bf = op == 'bfdot'
        return f'{op} v0.4s, v1.' + ('8h' if bf else '16b') + ', v2.' + (('2h[1]' if bf else '4b[1]') if cls == 'asimdelem' else '8h' if bf else '16b')
    if op in ('smmla', 'ummla', 'usmmla', 'bfmmla'):
        arr = '8h' if op == 'bfmmla' else '16b'
        return f'{op} v0.4s, v1.{arr}, v2.{arr}'
    if op == 'bfmlal':
        return 'bfmlalb v0.4s, v1.8h, ' + ('v2.h[1]' if cls == 'asimdelem' else 'v2.8h')
    if op == 'bfcvtn':
        return 'bfcvtn v0.4h, v1.4s'
    if cls == 'asimdmisc':
        return f'{op} v0.4s, v1.4s'
    # Scalar FP instruction names have a precision tag before the family.
    if tags and tags[-1] in ('float2int', 'float2fix'):
        if op == 'fjcvtzs':
            return 'fjcvtzs w0, d1'
        bits = 64 if '64' in cls else 32
        p = 'x' if bits == 64 else 'w'
        d, n = ('h0', f'{p}1') if cls.startswith('H') else (f'{p}0', 'h1')
        return f'{op} {d}, {n}' + (', #1' if tags[-1] == 'float2fix' else '')
    if op == 'bfcvt':
        return 'bfcvt h0, s1'
    precision = cls.lower()
    if tags == ['floatdp1']:
        return f'{op} {precision}0, {precision}1'
    if tags == ['floatdp2']:
        return f'{op} h0, h1, h2'
    if tags == ['floatdp3']:
        return f'{op} h0, h1, h2, h3'
    if tags == ['floatcmp']:
        return f'{op} h0, ' + ('#0.0' if cls == 'HZ' else 'h1')
    if tags == ['floatccmp']:
        return f'{op} h0, h1, #15, eq'
    if tags == ['floatsel']:
        return f'{op} h0, h1, h2, eq'
    if tags == ['floatimm']:
        return 'fmov h0, #1.0'
    raise AssertionError(f'Unhandled numeric form {name}')


def generate():
    records = {r['name']: r for r in json.loads((ROOT / 'isa/a64.json').read_text())['instructions']}
    names = [s for s in (ROOT / 'isa/m5-numeric.txt').read_text().splitlines() if s and not s.startswith('#')]
    return ('# Generated by tools/numeric_cases.py; names from pinned Arm AARCHMRS.\n'
            '# Arm-derived names: BSD-3-Clause; see ../isa/LICENSE-ARM.\n'
            + ''.join(f'{name}\t{case(records[name])}\n' for name in names))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'tests/numeric-cases.txt'
    output = generate()
    if args.check:
        assert target.read_text() == output, 'numeric-cases.txt is stale'
    else:
        target.write_text(output)

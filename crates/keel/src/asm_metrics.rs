//! JSON transport for the assembler's exact x86 encoding report.
use keel_asm::x86::{Features, RegionKind};
use serde_json::json;

pub fn x86(source: &str, features: Features) -> Result<String, String> {
    let (_, report) = keel_asm::x86::assemble_object_with_metrics_and_binary_inputs(
        source,
        keel_asm::x86::Syntax::Intel,
        features,
        &mut crate::input::binary_input,
    )
    .map_err(|e| e.to_string())?;
    let sections: Vec<_> = report.sections.iter().enumerate().map(|(index,s)| json!({
        "index":index,"name":s.name,"size":s.size,"executable":s.executable,"nobits":s.nobits,
    })).collect();
    let regions: Vec<_> = report.regions.iter().map(|r| {
        let branch = r.branch.as_ref().map(|b| json!({"displacement_bytes":b.displacement_bytes,
            "displacement":b.displacement,"target_offset":b.target_offset}));
        let relocations: Vec<_> = r.relocations.iter().map(|f| json!({"offset":f.offset,"width":f.width,"kind":f.kind.r_type(),"name":f.kind.name()})).collect();
        json!({"kind":match r.kind {RegionKind::Instruction=>"instruction",RegionKind::Alignment=>"alignment",RegionKind::Data=>"data",_=>unreachable!("known assembler region kind")},
            "section":r.section,"line":r.line,"offset":r.offset,"size":r.size,
            "bytes":r.bytes,"instruction":r.instruction,"prefixes":r.prefixes,"branch":branch,"relocations":relocations})
    }).collect();
    let sum = |kind| {
        report
            .regions
            .iter()
            .filter(|r| r.kind == kind)
            .map(|r| r.size)
            .sum::<u64>()
    };
    let output = json!({"schema_version":2,"target":"x86_64-unknown-linux-gnu",
        "features":features.names().collect::<Vec<_>>(),"sections":sections,"regions":regions,
        "instruction_bytes":sum(RegionKind::Instruction),"alignment_bytes":sum(RegionKind::Alignment),"data_bytes":sum(RegionKind::Data),
        "text_bytes":report.sections.iter().filter(|s|s.executable).map(|s|s.size).sum::<u64>(),
        "scope":"Final relocatable-object layout. Relocation fields are placeholders; data includes unclassified/generated bytes and NOBITS reservations. No CPU timing model."});
    serde_json::to_string_pretty(&output)
        .map(|s| s + "\n")
        .map_err(|e| e.to_string())
}

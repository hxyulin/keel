#!/usr/bin/env python3
"""Generate measured M5 alternative costs; do not invent missing entries."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "suite/reports/apple-m5-integer-2026-10-15.json"
OUTPUT = ROOT / "crates/keel-codegen/src/tuning/apple_m5.rs"


def generate(path):
    report = json.loads(path.read_text())
    if not report["cpu"].startswith("Apple M5") or report["unit"] != "nanoseconds per operation":
        raise ValueError("expected native Apple M5 elapsed-time calibration")
    if report["pairs"] < 3:
        raise ValueError("insufficient paired measurements")
    rows = []
    for bits in [32, 64]:
        for constant, shift in [(3, 1), (5, 2), (9, 3)]:
            pair = []
            for streams in [1, 8]:
                matches = [row for row in report["results"] if (row["bits"], row["multiplier"], row["streams"]) == (bits, constant, streams)]
                if len(matches) != 1:
                    raise ValueError("missing or duplicated calibration")
                pair.append(matches[0])
            chain, parallel = pair
            rows.append(f"Alternative {{ bits: {bits}, constant: {constant}, shift: {shift}, chain_ratio_upper: {chain['ratio_95_interval'][1]!r}, parallel_ratio: {parallel['after_over_before']!r} }},")
    source = "\n".join([
        "// Generated by suite/generate_m5_tuning.py; do not edit.",
        "// Native Apple M5 Max measurements, not LLVM scheduling estimates.",
        f"// Calibration SHA-256: {hashlib.sha256(path.read_bytes()).hexdigest()}",
        "use super::Alternative;", "pub(super) const MULTIPLY_ALTERNATIVES: &[Alternative] = &[", *rows, "];",
    ])
    return subprocess.run(["rustfmt", "--edition", "2024"], input=source, text=True, capture_output=True, check=True).stdout


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate(REPORT)
    if args.check:
        if OUTPUT.read_text() != output:
            parser.exit(1, "M5 tuning costs are stale\n")
    else:
        OUTPUT.write_text(output)

#!/usr/bin/env python3
"""Compare prebuilt x86 assemblers on fixed Keel source and the system linker.

Run on an otherwise idle Linux host. Prepared inputs are read only. Runtime
benchmarks use repository scripts, not the writable prepared fixture trees.
"""
import argparse
import collections
import json
import os
import platform
import statistics
import struct
import subprocess
import time
from pathlib import Path

from compare_native_toolchain import invoke, paired_summary, sha, text_section


def elf_sizes(path, out):
    data = path.read_bytes()
    at = struct.unpack_from("<Q", data, 40)[0]
    size, count, strings = struct.unpack_from("<HHH", data, 58)
    headers = [struct.unpack_from("<IIQQQQIIQQ", data, at + i * size) for i in range(count)]
    h = headers[strings]
    names = data[h[4]:h[4] + h[5]]
    sections = {names[h[0]:].split(b"\0")[0].decode(): h[5] for h in headers}
    symbols = collections.Counter()
    for h in headers:
        if h[1] != 2:
            continue
        sh = headers[h[6]]
        names = data[sh[4]:sh[4] + sh[5]]
        for offset in range(h[4], h[4] + h[5], h[9]):
            index = struct.unpack_from("<I", data, offset)[0]
            name = names[index:].split(b"\0")[0]
            symbols["total"] += 1
            if name.startswith(b".L"):
                symbols["dot_L"] += 1
    stripped = out / (path.name + ".stripped")
    invoke(["strip", "-s", "-o", stripped, path])
    return {"path": str(path), "sha256": sha(path), "bytes": len(data),
            "text_bytes": sections[".text"], "stripped_bytes": stripped.stat().st_size,
            "sections": sections, "symbols": dict(symbols)}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--before", type=Path, required=True)
    p.add_argument("--after", type=Path, required=True)
    p.add_argument("--prepared", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--cpu", type=int, default=2)
    p.add_argument("--assembly-pairs", type=int, default=5)
    p.add_argument("--runtime-pairs", type=int, default=11)
    a = p.parse_args()
    if min(a.assembly_pairs, a.runtime_pairs) < 3:
        p.error("use at least three paired samples")
    for name in ["before", "after", "prepared", "out"]:
        setattr(a, name, getattr(a, name).resolve())
    if a.out == a.prepared or a.out.is_relative_to(a.prepared):
        p.error("output must be outside prepared inputs")
    os.sched_setaffinity(0, {a.cpu})
    a.out.mkdir(parents=True, exist_ok=True)
    root = Path(__file__).resolve().parents[1]
    report = {"base_commit": "426d6fc8fa61f74c38dfbc892edf69afd1554278",
              "host": platform.node(), "platform": platform.platform(),
              "cpu": a.cpu, "clang": invoke(["clang", "--version"]).decode().splitlines()[0],
              "binaries": {n: {"path": str(path), "sha256": sha(path)}
                           for n, path in [("before", a.before), ("after", a.after)]},
              "method": "Prebuilt binaries, one fixed .s per input generated by before compiler; "
                        "serial warm assembly batches; same Clang system linker; "
                        "one runtime warmup then alternating paired runs, CPU affinity inherited. "
                        "Runtime includes startup. No Clang C-codegen comparison.",
              "modes": {}}

    def save():
        (a.out / "report.json").write_text(json.dumps(report, indent=2) + "\n")

    def measure(commands, pairs, stdin=None, batches=False):
        samples = {name: [] for name in commands}
        expected = None
        for iteration in range(pairs + 1):
            order = list(commands)
            if iteration % 2:
                order.reverse()
            for name in order:
                start = time.perf_counter_ns()
                if batches:
                    for command in commands[name]:
                        invoke(command)
                else:
                    output = invoke(commands[name], input=stdin)
                    if expected is None:
                        expected = output
                    assert output == expected, commands[name]
                elapsed = (time.perf_counter_ns() - start) / 1e6
                if iteration:
                    samples[name].append(elapsed)
        return paired_summary(samples, "before")

    for mode, flags in [("baseline", []), ("opt", ["-O"])]:
        entry = {"inputs": [], "suites": {}}
        report["modes"][mode] = entry
        batches = {name: [] for name in ["before", "after", "clang"]}
        objects = {}
        for suite in ["lua", "quickjs", "sqlite"]:
            out = a.out / mode / suite
            out.mkdir(parents=True, exist_ok=True)
            objects[suite] = {name: [] for name in batches}
            for source in sorted((a.prepared / suite / "pre").glob("*.i")):
                asm = out / (source.stem + ".s")
                invoke([a.before, "cc", *flags, source, "-o", asm])
                info = {"suite": suite, "source": str(source), "source_sha256": sha(source),
                        "asm": str(asm), "asm_sha256": sha(asm), "objects": {}}
                for name in batches:
                    obj = out / (source.stem + f".{name}.o")
                    command = (["clang", "-x", "assembler", "-c", asm] if name == "clang"
                               else [getattr(a, name), "asm", "--target", "x86_64-unknown-linux-gnu", asm])
                    command += ["-o", obj]
                    invoke(command)
                    batches[name].append(command)
                    objects[suite][name].append(obj)
                    info["objects"][name] = {"bytes": obj.stat().st_size,
                                             "text_bytes": len(text_section(obj)), "sha256": sha(obj)}
                entry["inputs"].append(info)
        assert len(entry["inputs"]) == 44
        entry["assembly"] = measure(batches, a.assembly_pairs, batches=True)
        save()
        print(f"{mode}: assembly after/before = {entry['assembly']['after']['median_paired_ratio']:.4f}", flush=True)
        for suite, binary in [("lua", "lua"), ("quickjs", "qjs"), ("sqlite", "sqlite3")]:
            out = a.out / mode / suite
            result = {"executables": {}, "benchmarks": {}}
            entry["suites"][suite] = result
            for name, paths in objects[suite].items():
                exe = out / (binary + "-" + name)
                invoke(["clang", *paths, "-lm", "-lpthread", "-ldl", "-o", exe])
                result["executables"][name] = elf_sizes(exe, out)
            benches = ["fib", "sort", "string", "float"] if suite == "lua" else ["fib", "sort", "string"]
            if suite == "sqlite":
                benches = ["queries"]
            for bench in benches:
                stdin = None
                if suite == "lua":
                    args = [root / "suite/lua/bench.lua", bench]
                elif suite == "quickjs":
                    args = ["--stack-size", "4194304", root / "suite/quickjs/bench.js", bench]
                else:
                    args, stdin = [":memory:"], (root / "suite/sqlite/bench.sql").read_bytes()
                commands = {name: [info["path"], *args] for name, info in result["executables"].items()}
                result["benchmarks"][bench] = measure(commands, a.runtime_pairs, stdin=stdin)
                print(f"{mode}/{suite}/{bench}: after/before = {result['benchmarks'][bench]['after']['median_paired_ratio']:.4f}", flush=True)
                save()
        ratios = [b["after"]["median_paired_ratio"] for s in entry["suites"].values()
                  for b in s["benchmarks"].values()]
        entry["runtime_geomean_after_before"] = statistics.geometric_mean(ratios)
        save()


if __name__ == "__main__":
    main()

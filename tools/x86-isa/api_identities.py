"""Keel's explicit public x86 API shapes, independent of ISA encodings.

The ordered schema preserves enum layout and payload types. Baseline spellings
run before wrapper dispatch, except Pclmulqdq, whose precedence stays handwritten.
This module generates identities and static names only, never instruction semantics.
"""
import json

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
PAYLOADS = {
    'Core': 'CoreOpcode', 'X87': 'X87Opcode', 'Fixed': 'FixedOpcode',
    'V2': 'V2Opcode', 'Extension': 'ExtensionOpcode', 'V3': 'V3Opcode',
    'Jcc': 'u8', 'Setcc': 'u8', 'Cmovcc': 'u8',
}


def outputs(root, output, opcode_identities):
    schema = json.loads((root / 'api-identities.json').read_text())
    rows = schema['baseline']
    variants = [r['variant'] for r in rows]
    spellings = [s for r in rows for s in r.get('spellings', [])]
    if len(set(variants)) != len(variants) or len(set(spellings)) != len(spellings):
        raise ValueError('duplicate baseline identity or spelling')
    if {r['variant']: r['payload'] for r in rows if 'payload' in r} != PAYLOADS:
        raise ValueError('baseline payload API changed; update explicit shape policy')
    for row in rows:
        if 'payload' in row:
            if 'mnemonic' in row or 'spellings' in row:
                raise ValueError('dynamic baseline names must stay handwritten')
        elif not row.get('mnemonic') or not row.get('spellings') and row.get('parse') != 'fallback':
            raise ValueError('baseline static identity needs a name and spellings')
        if 'parse' in row and (row['variant'] != 'Pclmulqdq' or row['parse'] != 'fallback'):
            raise ValueError('unsupported baseline parsing policy')
    lines = [HEADER, '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub enum Opcode {']
    for row in rows:
        lines.extend('    ' + comment for comment in row.get('comments', []))
        payload = '(' + row['payload'] + ')' if 'payload' in row else ''
        lines.append(f'    {row["variant"]}{payload},')
    lines += ['}', 'impl Opcode {', '    fn parse_baseline(name: &str) -> Option<Self> {',
              '        Some(match name {']
    for row in rows:
        if row.get('spellings'):
            names = ' | '.join(json.dumps(s) for s in row['spellings'])
            lines.append(f'            {names} => Self::{row["variant"]},')
    lines += ['            _ => return None,', '        })', '    }', '}', '']
    # The caller supplies dynamic arms. Expanding one exhaustive match lets Rust
    # check that every public variant has either a static or a dynamic name.
    names = [HEADER, 'macro_rules! baseline_mnemonic {',
             '    ($opcode:expr, { $($pattern:pat => $name:expr,)* }) => {',
             '        match $opcode {']
    names += [f'            Opcode::{r["variant"]} => {json.dumps(r["mnemonic"])},'
              for r in rows if 'payload' not in r]
    names += ['            $($pattern => $name,)*', '        }', '    };', '}', '']
    return {output.with_name('baseline_opcodes.rs'): '\n'.join(lines),
            output.with_name('baseline_mnemonics.rs'): '\n'.join(names),
            output.with_name('x87_opcodes.rs'): opcode_identities('X87Opcode', schema['x87'])}

"""Generate source witnesses, never expected bytes, from exposed binding data."""
import json
import re

import evex


def evex_sources(root, att=False):
    rows = sorted(evex.load(root), key=lambda r: r['mnemonic'])
    cases = []
    aliases = {(name, width): alias for alias, (name, width, _) in evex.att_aliases(rows).items()}
    for index, row in enumerate(rows):
        f, e = row['filters'], row.get('evex', {})
        vector = int(e.get('vector_length', f.get('vector_length', 128)))
        element = int(e.get('element_size', 0)) // 8
        tuple_ = e.get('tuple_type', '')
        scale = evex.tuple_scale(row)
        operands = []
        att_operands = []
        for o in row['operands']:
            if not o.get('visible', True) or o.get('encoding') == 'mask':
                continue
            kind, encoding = o['operand_type'], o.get('encoding')
            number = {'modrm_reg': 17, 'ndsndd': 22, 'modrm_rm': 29}.get(encoding, 0)
            if kind in ('xmm', 'ymm', 'zmm'):
                operand = kind + str(number)
            elif kind == 'mask':
                operand = 'k' + str(number % 7 + 1)
            elif kind in ('gpr32', 'gpr64'):
                operand = 'r10' + ('d' if kind == 'gpr32' else '')
            elif kind == 'imm':
                operand = '3'
            elif kind.startswith('mem'):
                size = o.get('width32', scale) * 8
                width = {8: 'byte', 16: 'word', 32: 'dword', 64: 'qword',
                         128: 'xmmword', 256: 'ymmword', 512: 'zmmword'}[size]
                index_reg = {'mem_vsibx': 'xmm23', 'mem_vsiby': 'ymm23', 'mem_vsibz': 'zmm23'}.get(kind, 'r14')
                operand = f'{width} ptr [r13+{index_reg}*4+{scale * 127}]'
            else:
                raise ValueError('no smoke operand for ' + kind)
            operands.append(operand)
            if kind.startswith('mem'):
                att_operands.append(f'{scale * 127}(%r13,%{index_reg},4)')
            elif kind == 'imm':
                att_operands.append('$' + operand)
            else:
                att_operands.append('%' + operand)
        if e.get('mask_mode') in ('allowed', 'required'):
            operands[0] += '{k2}'
            att_operands[0] += '{%k2}'
            if 'mask_flags' not in e or 'accepts_zero_mask' in e['mask_flags']:
                operands[0] += '{z}'
                att_operands[0] += '{z}'
        if f.get('evex_b') == '1' and e.get('functionality') in ('rc', 'sae'):
            at = len(operands) - 1 if row['operands'][-1]['operand_type'] in ('imm', 'gpr32', 'gpr64') else len(operands)
            operands.insert(at, '{rn-sae}' if e['functionality'] == 'rc' else '{sae}')
            att_operands.insert(at, '{rn-sae}' if e['functionality'] == 'rc' else '{sae}')
        att_name = row['mnemonic']
        if att:
            for operand in row['operands']:
                if operand['operand_type'] == 'mem':
                    att_name = aliases.get((row['mnemonic'], operand.get('width32', scale) * 8), att_name)
        explicit = row['encoding'] == 'evex' and not (att and f.get('evex_b') == '1' and e.get('functionality') in ('rc', 'sae'))
        source = ('{evex} ' if explicit else '') + (att_name if att else row['mnemonic']) + ' ' + ','.join(att_operands[::-1] if att else operands)
        cases.append(f'{index}|{row["meta_info"]["isa_set"]}|{source}')
        # Embedded broadcast is a second exposed interpretation of this form.
        if e.get('functionality') == 'bc':
            broadcast = scale // element
            if att and att_name != row['mnemonic']:
                source = source.replace(att_name + ' ', row['mnemonic'] + ' ', 1)
            source = re.sub(r'\b(?:zmmword|ymmword|xmmword|qword|dword|word|byte) ptr',
                            ('dword' if element == 4 else 'qword') + ' ptr', source)
            source = re.sub(r'(\))' if att else r'(\[[^\]]+\])', lambda m: m[0] + '{1to' + str(broadcast) + '}', source)
            cases.append(f'{index}|{row["meta_info"]["isa_set"]}|{source}')
    return '# Generated by tools/x86-isa/generate.py; no expected bytes.\n' + '\n'.join(cases) + '\n'


def compiler_source(root):
    source = '; Generated by tools/x86-isa/generate.py; compile only.\n'
    for file in ['system-intrinsics.json', 'query-bindings.json']:
        for row in json.loads((root / file).read_text())['intrinsics']:
            params = [t.lower() for t in row['params']]
            params += ['ptr', 'ptr', 'ptr']
            source += f'func @binding_{row["id"]}({",".join(params)}) {{\nentry('
            source += ','.join(f'v{n}:{t}' for n, t in enumerate(params)) + '):\n'
            args = [f'v{n}' for n in range(len(row['params']))]
            next_ = len(params)
            if row.get('binding', {}).get('kind') == 'port_io' and row['binding']['immediate']:
                source += f' v{next_} = iconst.i16 224\n'
                args[0] = f'v{next_}'
                next_ += 1
            results = [f'v{next_ + n}' for n in range(len(row['returns']))]
            source += ' ' + (','.join(results) + ' = ' if results else '') + f'intrinsic {row["name"]}({",".join(args)})\n'
            for n, result in enumerate(results):
                source += f' store {result},v{len(row["params"]) + n}\n'
            for n in range(len(row['params'])):
                source += f' store v{n},v{len(row["params"]) + 2}\n'
            source += ' return\n}\n'
    return source


def outputs(root):
    project = root.parents[1]
    return {project / 'crates/keel-disasm/tests/generated/x86-evex-smoke.txt': evex_sources(root),
            project / 'crates/keel-disasm/tests/generated/x86-evex-smoke-att.txt': evex_sources(root, att=True),
            project / 'crates/keel-codegen/tests/generated/x86-binding-smoke.ir': compiler_source(root)}

"""Generate regular AT&T dialect mappings; operand grammar stays in Rust."""
import json
import re

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
KEYS = {'scalar_suffixes', 'scalar', 'far_widths', 'extensions', 'legacy_x87_memory',
        'aliases', 'integer_conversions', 'packed_conversions', 'packed_suffixes', 'x87_memory'}


def generate(schema, identities, core, adapters):
    if set(schema) != KEYS:
        raise ValueError('unknown or missing AT&T rule groups')
    domains = {
        'baseline': {r['variant'] for r in identities['baseline'] if 'payload' not in r},
        'core': {r['variant'] for r in core if 'fields' not in r},
        'fixed': {r['variant'] for r in adapters['identities']['fixed']},
        'v2': {r['variant'] for r in adapters['identities']['v2']},
        'v3': {r['variant'] for r in adapters['identities']['v3']},
        'conditions': {'Cmovcc', 'Setcc', 'Jcc'},
    }
    x87_names = {r['variant']: r['mnemonic'] for r in identities['x87']}

    def opcode(name, group='baseline'):
        if group not in domains or name not in domains[group]:
            raise ValueError(f'unknown AT&T opcode {group}/{name}')
        if group == 'conditions':
            return f'Opcode::{name}(_)'
        if group == 'baseline':
            return f'Opcode::{name}'
        return f'Opcode::{group.capitalize()}({group.capitalize()}Opcode::{name})'

    def spelling(name):
        if not isinstance(name, str) or not re.fullmatch('[a-z][a-z0-9]*', name):
            raise ValueError('invalid AT&T spelling')
        return json.dumps(name)

    def width(value):
        if type(value) is not int or value not in (8, 16, 32, 48, 64, 80, 128, 256):
            raise ValueError('invalid AT&T width')
        return value

    def fields(row, expected):
        if set(row) != set(expected):
            raise ValueError('unknown or missing AT&T row fields')

    lines = [HEADER]

    def function(name, args, returns, arms, fallback='None'):
        lines.extend([f'fn {name}({args}) -> {returns} {{', '    match ' +
                      ('op' if args.startswith('op:') else 'name') + ' {'])
        lines.extend(f'        {pattern} => {value},' for pattern, value in arms)
        lines.extend([f'        _ => {fallback},', '    }', '}', ''])

    for name, table, allowed in [('bits', schema['scalar_suffixes'], {8, 16, 32, 64}),
                                  ('packed_bits', schema['packed_suffixes'], {128, 256})]:
        if not table or len(set(table.values())) != len(table):
            raise ValueError('duplicate or empty AT&T suffix widths')
        arms = []
        for suffix, bits in table.items():
            if len(suffix) != 1 or not suffix.isascii() or not suffix.islower() or bits not in allowed:
                raise ValueError('invalid AT&T suffix rule')
            arms.append((f"b'{suffix}'", f'Some({width(bits)})'))
        function(name, 'name: u8', 'Option<u16>', arms)

    if set(schema['scalar']) != {'baseline', 'core', 'v3', 'conditions'}:
        raise ValueError('unknown or missing scalar opcode groups')
    patterns = []
    for group, names in schema['scalar'].items():
        if len(names) != len(set(names)):
            raise ValueError('duplicate scalar opcode')
        patterns += [opcode(name, group) for name in names]
    lines += ['fn scalar(op: Opcode) -> bool {',
              '    if let Opcode::Extension(op) = op { return op.scalar_suffix(); }',
              '    matches!(op, ' + ' | '.join(patterns) + ')', '}', '']

    arms, seen = [], set()
    for row in schema['far_widths']:
        fields(row, ('names', 'width'))
        if not row['names']:
            raise ValueError('empty far-width names')
        for name in row['names']:
            if name in seen:
                raise ValueError('duplicate far-width spelling')
            seen.add(name)
        arms.append((' | '.join(spelling(n) for n in row['names']), f'Some({width(row["width"])})'))
    function('far_width', 'name: &str', 'Option<u16>', arms)

    for key, name, returns in [('extensions', 'extension', 'Option<(Opcode, u16, u16)>'),
                               ('legacy_x87_memory', 'legacy_x87_memory', 'Option<(Opcode, u16)>'),
                               ('aliases', 'alias', 'Option<Opcode>')]:
        arms, seen = [], set()
        for row in schema[key]:
            expected = {'name', 'opcode'}
            if key == 'extensions': expected |= {'source', 'destination'}
            if key == 'legacy_x87_memory': expected |= {'width'}
            if 'group' in row: expected |= {'group'}
            fields(row, expected)
            if row['name'] in seen:
                raise ValueError('duplicate AT&T spelling in ' + key)
            seen.add(row['name'])
            op = opcode(row['opcode'], row.get('group', 'baseline'))
            if key == 'extensions':
                source, destination = width(row['source']), width(row['destination'])
                if not source < destination <= 64:
                    raise ValueError('extension must widen a scalar operand')
                value = f'({op}, {source}, {destination})'
            elif key == 'legacy_x87_memory': value = f'({op}, {width(row["width"])})'
            else: value = op
            arms.append((spelling(row['name']), f'Some({value})'))
        function(name, 'name: &str', returns, arms)

    arms, seen = [], set()
    for row in schema['integer_conversions']:
        fields(row, ('opcode', 'group', 'operand'))
        pattern = opcode(row['opcode'], row['group'])
        if pattern in seen or type(row['operand']) is not int or row['operand'] not in (0, 1, 2):
            raise ValueError('invalid or duplicate conversion operand')
        seen.add(pattern)
        arms.append((pattern, f'Some({row["operand"]})'))
    function('conversion_operand', 'op: Opcode', 'Option<usize>', arms)
    packed = schema['packed_conversions']
    if len(packed) != len(set(packed)):
        raise ValueError('duplicate packed conversion')
    pattern = ' | '.join(opcode(n, 'v3') for n in packed)
    lines.extend(['fn packed_conversion(op: Opcode) -> bool {',
                  f'    matches!(op, {pattern})' if packed else '    false', '}', ''])

    # Additional x87 spellings have a separate lookup and keep their existing
    # precedence over the baseline x87 names in the AT&T parser.
    arms, seen = [], set()
    for row in schema['x87_memory']:
        fields(row, ('opcode', 'suffixes'))
        if row['opcode'] not in x87_names or not row['suffixes']:
            raise ValueError('unknown x87 memory opcode or empty suffixes')
        for suffix, bits in row['suffixes'].items():
            if suffix not in ('s', 'l'):
                raise ValueError('invalid x87 suffix')
            name = x87_names[row['opcode']] + suffix
            if name in seen:
                raise ValueError('duplicate x87 memory spelling')
            seen.add(name)
            arms.append((spelling(name), f'Some((X87Opcode::{row["opcode"]}, {width(bits)}))'))
    function('x87_memory', 'name: &str', 'Option<(X87Opcode, u16)>', arms)
    return '\n'.join(lines)


def outputs(root, output):
    load = lambda name: json.loads((root / name).read_text())
    return {output.with_name('att_rules.rs'): generate(load('att-rules.json'),
            load('api-identities.json'), load('core-identities.json'), load('keel-adapters.json'))}

"""Generate API identities and condition names, never operand grammar or effects."""
import json
import re

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
FIELDS = {
    'String': [['kind', 'StringKind'], ['width', 'u16'], ['repeat', 'Repeat'],
               ['address32', 'bool'], ['segment', 'Option<u8>']],
    'Xlat': [['address32', 'bool'], ['segment', 'Option<u8>']],
    'Loop': [['kind', 'LoopKind'], ['address32', 'bool']],
    'Enter': [['operand16', 'bool']], 'RetFar': [['width', 'u16']],
}


def core_sources(rows):
    variants, spellings, fields = set(), set(), {}
    for row in rows:
        if set(row) != ({'variant', 'fields'} if 'fields' in row else
                        {'variant', 'mnemonic', 'spellings'}):
            raise ValueError('unknown or missing core identity fields')
        name = row['variant']
        if not re.fullmatch(r'[A-Z][A-Za-z0-9_]*', name) or name in variants:
            raise ValueError('invalid or duplicate core identity')
        variants.add(name)
        if 'fields' in row:
            fields[name] = row['fields']
            continue
        if not row['mnemonic'] or not row['spellings']:
            raise ValueError('static core identity needs names')
        for spelling in row['spellings']:
            if not re.fullmatch(r'[a-z0-9.]+', spelling) or spelling in spellings:
                raise ValueError('invalid or duplicate core spelling')
            spellings.add(spelling)
    if fields != FIELDS:
        raise ValueError('core payload API changed; update explicit shape policy')
    enum = [HEADER, '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub enum CoreOpcode {']
    for row in rows:
        if 'fields' in row:
            enum += [f'    {row["variant"]} {{']
            enum += [f'        {name}: {ty},' for name, ty in row['fields']]
            enum += ['    },']
        else:
            enum += [f'    {row["variant"]},']
    enum += ['}', 'impl CoreOpcode {', '    fn parse_static(name: &str) -> Option<Self> {',
             '        Some(match name {']
    names = [HEADER, 'macro_rules! core_mnemonic {',
             '    ($opcode:expr, { $($pattern:pat => $name:expr,)* }) => {',
             '        match $opcode {']
    for row in rows:
        if 'fields' in row:
            continue
        aliases = ' | '.join(json.dumps(s) for s in row['spellings'])
        enum += [f'            {aliases} => Self::{row["variant"]},']
        names += [f'            Self::{row["variant"]} => {json.dumps(row["mnemonic"])},']
    enum += ['            _ => return None,', '        })', '    }', '}', '']
    names += ['            $($pattern => $name,)*', '        }', '    };', '}', '']
    return '\n'.join(enum), '\n'.join(names)


def condition_source(rows):
    if len(rows) != 16 or [r['code'] for r in rows] != list(range(16)):
        raise ValueError('condition codes must cover 0 through 15 in order')
    aliases = set()
    for row in rows:
        if set(row) != {'code', 'name', 'aliases', 'isa_name'}:
            raise ValueError('unknown or missing condition fields')
        if row['name'] not in row['aliases'] or row['isa_name'] not in row['aliases']:
            raise ValueError('condition names must be aliases')
        for alias in row['aliases']:
            if not re.fullmatch(r'[a-z]+', alias) or alias in aliases:
                raise ValueError('invalid or duplicate condition alias')
            aliases.add(alias)
    lines = [HEADER, '/// Parse a condition suffix without a j/set/cmov prefix.',
             'pub fn parse_condition_code(name: &str) -> Option<u8> {', '    Some(match name {']
    for row in rows:
        names = ' | '.join(json.dumps(a) for a in row['aliases'])
        lines += [f'        {names} => {row["code"]},']
    lines += ['        _ => return None,', '    })', '}', '']
    for function, key, doc in [('condition_code_name', 'name', 'Public assembly suffix'),
                               ('isa_condition_code_name', 'isa_name', 'Imported ISA suffix')]:
        lines += [f'/// {doc}. Invalid condition numbers have no name.',
                  f'pub fn {function}(code: u8) -> Option<&\'static str> {{',
                  '    Some(match code {']
        lines += [f'        {r["code"]} => {json.dumps(r[key])},' for r in rows]
        lines += ['        _ => return None,', '    })', '}', '']
    return '\n'.join(lines)


def outputs(root, output):
    enums, names = core_sources(json.loads((root / 'core-identities.json').read_text()))
    return {output.with_name('core_opcodes.rs'): enums,
            output.with_name('core_mnemonics.rs'): names,
            output.with_name('condition_codes.rs'):
                condition_source(json.loads((root / 'condition-codes.json').read_text()))}

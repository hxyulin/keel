"""Generate cumulative CPU-level constructors from explicit profile policy."""
import json
import re


def resolve(schema, fields):
    if set(schema) != {'default', 'profiles'} or not schema['profiles']:
        raise ValueError('unknown or missing CPU profile fields')
    known = {r['field'] for r in fields}
    profiles, variants = {}, set()
    for row in schema['profiles']:
        if set(row) - {'variant', 'name', 'features', 'extends'} or not {'variant', 'name', 'features'} <= row.keys():
            raise ValueError('unknown or missing profile fields')
        if (not re.fullmatch('[A-Z][A-Za-z0-9]*', row['variant']) or
                not re.fullmatch('[a-z][a-z0-9]*', row['name']) or
                row['name'] in profiles or row['variant'] in variants):
            raise ValueError('invalid or duplicate CPU profile')
        if len(row['features']) != len(set(row['features'])) or set(row['features']) - known:
            raise ValueError('invalid CPU profile feature')
        profiles[row['name']] = row
        variants.add(row['variant'])
    if schema['default'] not in profiles:
        raise ValueError('unknown default CPU profile')
    def resolve(name, path):
        if name not in profiles:
            raise ValueError('unknown parent CPU profile')
        if name in path:
            raise ValueError('CPU profile inheritance cycle')
        row = profiles[name]
        own = set(row['features'])
        return own | (resolve(row['extends'], path | {name}) if 'extends' in row else set())
    resolved = {name: resolve(name, set()) for name in profiles}
    previous = set()
    for name, members in resolved.items():
        if not previous <= members:
            raise ValueError('CPU levels must be cumulative in order')
        previous = members
        for row in fields:
            if row['field'] in members and set(row.get('requires', [])) - members:
                raise ValueError('CPU profile lacks prerequisites: ' + name)
    return profiles, resolved


def generate(schema, fields):
    profiles, resolved = resolve(schema, fields)
    lines = ['// Generated by tools/x86-isa/generate.py from cpu-profiles.json; do not edit.',
             '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub enum CpuLevel {']
    lines += [f'    {row["variant"]},' for row in profiles.values()]
    lines += ['}', 'impl CpuLevel {', '    pub fn parse(name: &str) -> Result<Self, String> {',
              '        match name {']
    lines += [f'            "{name}" => Ok(Self::{row["variant"]}),' for name, row in profiles.items()]
    expected = ', '.join(profiles)
    lines += [f'            _ => Err(format!("unknown x86 CPU level `{{name}}`; expected {expected}")),',
              '        }', '    }', '}', 'impl Features {',
              '    pub const fn for_level(level: CpuLevel) -> Self {', '        match level {']
    for name, row in profiles.items():
        lines += [f'            CpuLevel::{row["variant"]} => Self {{']
        lines += [f'                {r["field"]}: true,' for r in fields if r['field'] in resolved[name]]
        lines += ['                ..Self::NONE', '            },']
    lines += ['        }', '    }', '}', 'impl Default for Features {',
              '    fn default() -> Self {',
              f'        Self::for_level(CpuLevel::{profiles[schema["default"]]["variant"]})',
              '    }', '}', '']
    return '\n'.join(lines)


def profile_table(schema, fields):
    profiles, resolved = resolve(schema, fields)
    lines = ['<!-- Generated by tools/x86-isa/generate.py; do not edit. -->',
             '# x86 CPU profiles', '', '| Profile | Default | Optional capabilities |',
             '|---|---|---|']
    for name in profiles:
        members = ', '.join('`' + r['field'] + '`' for r in fields
                            if r['field'] in resolved[name]) or 'None'
        lines.append(f'| {name} | {"yes" if name == schema["default"] else ""} | {members} |')
    return '\n'.join(lines) + '\n'


def outputs(root, output, fields):
    schema = json.loads((root / 'cpu-profiles.json').read_text())
    return {output.with_name('cpu_profiles.rs'): generate(schema, fields),
            root / 'cpu-profile-table.md': profile_table(schema, fields)}

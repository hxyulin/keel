"""Pinned AVX-512F forms, including its VEX-encoded mask-register operations."""
import hashlib
import json

import feature_fields
import table_support

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
FILTERS = {'modrm_mod', 'modrm_reg', 'modrm_rm', 'mandatory_prefix', 'vector_length',
           'rex_w', 'evex_b', 'evex_u', 'mode', 'address_size', 'feature_knc'}
TUPLES = {'fv', 'hv', 'fvm', 'hvm', 'qvm', 'ovm', 't1s', 't1f', 't2', 't4', 't8', 'm128', 'dup', 'gscat'}
KINDS = {'gpr32', 'gpr64', 'xmm', 'ymm', 'zmm', 'mask', 'mem', 'imm',
         'mem_vsibx', 'mem_vsiby', 'mem_vsibz'}


def load(root):
    source = (root / 'evex.json').read_bytes()
    provenance = json.loads((root / 'evex-source.json').read_text())
    if hashlib.sha256(source).hexdigest() != provenance['subset_sha256']:
        raise ValueError('EVEX subset hash mismatch')
    return validate(json.loads(source))


def validate(rows):
    if not isinstance(rows, list) or not rows:
        raise ValueError("empty AVX-512F inventory")
    ids = set()
    for row in rows:
        f, e = row['filters'], row.get('evex', {})
        if set(f) - FILTERS or f.get('evex_u', '1') != '1' or f.get('feature_knc', '0') != '0':
            raise ValueError('unknown EVEX filter')
        if row.get('encoding') not in ('evex', 'vex') or row['meta_info']['isa_set'] not in {'AVX512F_512', 'AVX512F_256', 'AVX512F_128', 'AVX512F_SCALAR', 'AVX512F_128N', 'AVX512F_KOP', 'AVX512_VPCLMULQDQ_512'}:
            raise ValueError('outside AVX-512F import scope')
        if (row['encoding'] == 'vex') != (row['meta_info']['isa_set'] == 'AVX512F_KOP'):
            raise ValueError('AVX-512F mask operations use VEX; vector forms use EVEX')
        if set(e) - {'vector_length', 'functionality', 'mask_mode', 'mask_flags', 'tuple_type', 'element_size', 'static_broadcast'}:
            raise ValueError('unknown EVEX property')
        if e.get('tuple_type') not in (None, *TUPLES) or e.get('functionality') not in (None, 'bc', 'rc', 'sae'):
            raise ValueError('unknown EVEX tuple/functionality')
        domains = {'modrm_mod': {'3', '!3'}, 'modrm_reg': set('01234567'), 'modrm_rm': set('01234567'),
                   'mandatory_prefix': {'none', '66', 'f2', 'f3'}, 'vector_length': {'128', '256', '512'},
                   'rex_w': {'0', '1'}, 'evex_b': {'0', '1'}, 'evex_u': {'1'},
                   'mode': {'64'}, 'address_size': {'!16'}, 'feature_knc': {'0'}}
        if not {'modrm_mod', 'mandatory_prefix'} <= f.keys() or row.get('opcode_map') not in ('0f', '0f38', '0f3a'):
            raise ValueError('missing EVEX opcode constraints or unsupported map')
        if row['encoding'] == 'evex' and not (e.get('vector_length') or f.get('vector_length')):
            raise ValueError('missing EVEX vector length')
        if row['encoding'] == 'evex' and any(o['operand_type'].startswith('mem') for o in row['operands']) and (not e.get('element_size') or not e.get('tuple_type')):
            raise ValueError('missing EVEX memory tuple/element size')
        if any(key in f and f[key] not in values for key, values in domains.items()):
            raise ValueError('unsupported EVEX filter value')
        if e.get('mask_mode', 'forbidden') not in ('allowed', 'required', 'forbidden') or e.get('element_size') not in (None, '8', '16', '32', '64'):
            raise ValueError('unsupported EVEX mask/element size')
        if not isinstance(e.get('mask_flags', []), list) or set(e.get('mask_flags', [])) - {'force_zero_mask', 'is_control_mask', 'accepts_zero_mask'}:
            raise ValueError('unknown EVEX mask flags')
        if e.get('vector_length') not in (None, '128', '256', '512') or e.get('static_broadcast') not in (None, '1to2', '1to4', '1to8', '1to16', '4to8', '4to16'):
            raise ValueError('unsupported EVEX length/static broadcast')
        if any(o.get('encoding') not in {'modrm_reg', 'modrm_rm', 'ndsndd', 'mask', 'uimm8'} for o in row['operands']):
            raise ValueError('unknown EVEX operand encoding')
        key = json.dumps(row, sort_keys=True)
        if key in ids:
            raise ValueError('duplicate EVEX source form')
        ids.add(key)
        if any(o['operand_type'] not in KINDS for o in row['operands']):
            raise ValueError('unknown EVEX operand')
    return rows


def tuple_scale(row):
    f, e = row['filters'], row.get('evex', {})
    vector = int(e.get('vector_length', f.get('vector_length', 128))) // 8
    element = int(e.get('element_size', 0)) // 8
    return {'fv': vector, 'fvm': vector, 'hv': vector // 2, 'hvm': vector // 2,
            'qvm': vector // 4, 'ovm': vector // 8, 't1s': element, 't1f': element,
            'gscat': element, 't2': element * 2, 't4': element * 4, 't8': element * 8,
            'm128': 16, 'dup': 8 if vector == 16 else vector}.get(e.get('tuple_type'), 1)


def att_aliases(rows):
    groups = {}
    for row in rows:
        operands = [o for o in row['operands'] if o.get('visible', True) and o.get('encoding') != 'mask']
        for index, operand in enumerate(operands):
            if operand['operand_type'] == 'mem' and operand.get('action', 'read') == 'read':
                key = (row['mnemonic'], tuple(o['operand_type'] for o in operands))
                groups.setdefault(key, set()).add((operand.get('width32', tuple_scale(row)) * 8, index))
    aliases = {}
    suffixes = {32: 'l', 64: 'q', 128: 'x', 256: 'y', 512: 'z'}
    for (mnemonic, _), widths in groups.items():
        if len({width for width, _ in widths}) > 1:
            for width, index in widths:
                if width not in suffixes:
                    raise ValueError('unsupported ambiguous AT&T memory width')
                value = (mnemonic, width, index)
                spelling = mnemonic + suffixes[width]
                if spelling in aliases and aliases[spelling] != value:
                    raise ValueError('ambiguous EVEX AT&T suffix')
                aliases[spelling] = value
    return aliases


def outputs(root, output, opcode_identities):
    rows = load(root)
    policy = feature_fields.closed_policy(json.loads((root / 'feature-fields.json').read_text()), json.loads((root / 'feature-policy.json').read_text()))
    def requirement(isa):
        if not policy.get(isa):
            raise ValueError('unclassified AVX-512 ISA: ' + isa)
        return policy[isa]
    def bits(fields):
        return 'Features { ' + ', '.join(f'{field}: true' for field in fields) + ', ..Features::NONE }'
    names = sorted({r['mnemonic'] for r in rows})
    identities = [dict(variant=name[0].upper() + name[1:], mnemonic=name) for name in names]
    lines = [HEADER, 'use super::super::evex::EvexForm;', 'use super::{IsaForm, IsaOperand, OperandSizeRule};', 'use crate::x86::Features;',
             '#[rustfmt::skip]', 'pub static EVEX_FORMS: &[EvexForm] = &[']
    operand_lists = table_support.OperandLists()
    for row in sorted(rows, key=lambda r: r['mnemonic']):
        f, e = row['filters'], row.get('evex', {})
        vector = int(e.get('vector_length', f.get('vector_length', 128)))
        operands = []
        for o in row['operands']:
            if o.get('visible', True) and o.get('encoding') != 'mask':
                widths = [o.get('width' + str(n), 0) for n in [16, 32, 64]]
                operands.append('IsaOperand { kind: %s, encoding: %s, register: "", widths: %s }' %
                                (json.dumps(o['operand_type']), json.dumps(o.get('encoding', '')), widths))
        mod = f['modrm_mod']
        attrs = dict(mnemonic=row['mnemonic'], vex=row['encoding'] == 'vex',
                     map={'0f': 1, '0f38': 2, '0f3a': 3}[row['opcode_map']],
                     byte=int(row['opcode'], 16), prefix={'none': 0, '66': 102, 'f2': 242, 'f3': 243}[f['mandatory_prefix']],
                     sizes=7, addresses=6, osz='default', mod_mask=8 if mod == '3' else 7,
                     reg_mask=1 << int(f['modrm_reg']) if 'modrm_reg' in f else 255,
                     rm_mask=1 << int(f['modrm_rm']) if 'modrm_rm' in f else 255,
                     w=int(f.get('rex_w', -1)), b=-1, vector=vector, rex2=-1,
                     lock=False, rep=False, repne=False, gather='is_gather' in row.get('flags', []),
                     ignore_mod=False, far=False, decode=True, group1=-1,
                     isa=row['meta_info']['isa_set'], extension=row['meta_info']['extension'])
        fields = ', '.join(f'{k}: {table_support.operand_size_rule(v) if k == "osz" else json.dumps(v)}'
                           for k, v in attrs.items())
        fields += ', cpl: ' + ('Some(%s)' % row['cpl'] if 'cpl' in row else 'None')
        fields += ', operands: ' + operand_lists.reference(operands)
        lines.append('EvexForm { form: IsaForm { ' + fields + ' }, ' +
                     'functionality: %s, tuple: %s, element: %s, mask: %s, zero: %s, required: %s, evex_b: %s, ll_mask: %s },' %
                     (json.dumps(e.get('functionality', '')), json.dumps(e.get('tuple_type', '')),
                      int(e.get('element_size', 0)), json.dumps(e.get('mask_mode', 'forbidden')),
                      str('mask_flags' not in e or 'accepts_zero_mask' in e['mask_flags']).lower(),
                      bits(requirement(row['meta_info']['isa_set'])),
                      int(f.get('evex_b', -1)), (1 << {'128': 0, '256': 1, '512': 2}[f['vector_length']]) if 'vector_length' in f else 15))
    lines += ['];', '']
    lines.extend(operand_lists.declarations())
    ordered_rows = sorted(rows, key=lambda r: r['mnemonic'])
    ordered = sorted(({'0f': 1, '0f38': 2, '0f3a': 3}[r['opcode_map']] * 256 + int(r['opcode'], 16), n)
                     for n, r in enumerate(ordered_rows) if r['encoding'] == 'evex')
    position, ranges = 0, []
    for key in range(1024):
        start = position
        while position < len(ordered) and ordered[position][0] == key:
            position += 1
        ranges.append((start, position))
    lines += ['#[rustfmt::skip]', 'pub(super) static DECODE_ORDER: &[u16] = &[',
              ','.join(str(n) for _, n in ordered), '];', '#[rustfmt::skip]',
              'pub(super) static DECODE_RANGES: &[(u16,u16)] = &[',
              ','.join(f'({a},{b})' for a, b in ranges), '];', '']
    opcode_source = opcode_identities('EvexMnemonic', identities)
    opcode_source += '\nimpl EvexMnemonic {\n    pub const fn required_features(self) -> Features {\n        match self {\n'
    for name, identity in zip(names, identities):
        sets = [set(requirement(r['meta_info']['isa_set'])) for r in rows if r['mnemonic'] == name]
        common = set.intersection(*sets)
        opcode_source += '            Self::' + identity['variant'] + ' => ' + bits(sorted(common)) + ',\n'
    opcode_source += '        }\n    }\n}\n'
    opcode_source += "\npub(super) fn att_alias(name: &str) -> Option<(&'static str, u16, usize)> {\n    Some(match name {\n"
    for alias, (name, width, index) in sorted(att_aliases(rows).items()):
        opcode_source += f'        "{alias}" => ("{name}", {width}, {index}),\n'
    opcode_source += '        _ => return None,\n    })\n}\n'
    return {output.with_name('evex_forms.rs'): '\n'.join(lines),
            output.with_name('evex_opcodes.rs'): opcode_source}

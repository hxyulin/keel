"""Generate mechanical feature APIs; CPU and dependency policy stays in Rust.

feature-fields.json order is the public struct and names() order. `explicit`
tracks target selection rather than a CPU capability, so it is not in the list.
"""
import json
import re


def validate(fields, policy):
    names, spellings = set(), set()
    for row in fields:
        field = row['field']
        if not re.fullmatch(r'[a-z][a-z0-9_]*', field) or field == 'explicit':
            raise ValueError(f'invalid feature field: {field}')
        if field in names:
            raise ValueError(f'duplicate feature field: {field}')
        names.add(field)
        for spelling in [field, *row.get('aliases', [])]:
            if not spelling or spelling in spellings:
                raise ValueError(f'duplicate or empty feature spelling: {spelling}')
            spellings.add(spelling)
    for isa, bits in policy.items():
        unknown = set(bits or []) - names
        if unknown:
            raise ValueError(f'unknown feature fields in policy {isa}: {sorted(unknown)}')


def generate(fields, policy):
    validate(fields, policy)
    names = [row['field'] for row in fields]
    lines = ['// Generated by tools/x86-isa/generate.py from feature-fields.json; do not edit.',
             '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub struct Features {']
    for row in fields:
        if 'doc' in row:
            lines.extend(f'    /// {line}' for line in row['doc'].splitlines())
        lines.append(f'    pub {row["field"]}: bool,')
    lines += ['    /// Tracks an explicit target even when its extension set is empty.',
              '    pub explicit: bool,', '}', 'impl Features {',
              '    pub const NONE: Self = Self {']
    lines += [f'        {name}: false,' for name in names]
    lines += ['        explicit: false,', '    };',
              '    pub fn contains(self, required: Self) -> bool {']
    lines += [('        ' if i == 0 else '            && ') +
              f'(!required.{name} || self.{name})' for i, name in enumerate(names)]
    lines += ['    }', '    fn feature_mut(&mut self, name: &str) -> Option<&mut bool> {',
              '        Some(match name {']
    for row in fields:
        spellings = ' | '.join(json.dumps(s) for s in [row['field'], *row.get('aliases', [])])
        lines.append(f'            {spellings} => &mut self.{row["field"]},')
    lines += ['            _ => return None,', '        })', '    }',
              "    pub fn names(self) -> impl Iterator<Item = &'static str> {", '        [']
    lines += [f'            (self.{name}, "{name}"),' for name in names]
    lines += ['        ]', '        .into_iter()',
              '        .filter_map(|(on, name)| on.then_some(name))', '    }', '}', '']
    return '\n'.join(lines)

"""Generate feature sets, stable fingerprints and prerequisite graph operations."""
import json
import re


def validate(fields, policy):
    names, spellings, bits = set(), set(), set()
    for row in fields:
        if set(row) - {'field', 'doc', 'aliases', 'bit', 'requires'} or not {'field', 'bit'} <= row.keys():
            raise ValueError('unknown or missing feature fields')
        field = row['field']
        if not re.fullmatch(r'[a-z][a-z0-9_]*', field) or field == 'explicit':
            raise ValueError(f'invalid feature field: {field}')
        if field in names:
            raise ValueError(f'duplicate feature field: {field}')
        names.add(field)
        bit = row['bit']
        if type(bit) is not int or not 0 <= bit < 64 or bit in bits:
            raise ValueError('invalid or duplicate feature bit')
        bits.add(bit)
        for spelling in [field, *row.get('aliases', [])]:
            if not re.fullmatch(r'[a-z][a-z0-9_]*', spelling) or spelling in ('none', 'explicit'):
                raise ValueError(f'invalid feature spelling: {spelling}')
            if spelling in spellings:
                raise ValueError(f'duplicate or empty feature spelling: {spelling}')
            spellings.add(spelling)
    graph = {r['field']: r.get('requires', []) for r in fields}
    for field, deps in graph.items():
        if len(deps) != len(set(deps)) or set(deps) - names:
            raise ValueError(f'invalid feature prerequisites: {field}')
    def visit(name, path):
        if name in path:
            raise ValueError('feature prerequisite cycle: ' + name)
        for dep in graph[name]:
            visit(dep, path | {name})
    for name in names:
        visit(name, set())
    for isa, required in policy.items():
        unknown = set(required or []) - names
        if unknown:
            raise ValueError(f'unknown feature fields in policy {isa}: {sorted(unknown)}')


def closed_policy(fields, policy):
    """Requirements are usable feature sets, including state prerequisites."""
    validate(fields, policy)
    graph = {r['field']: r.get('requires', []) for r in fields}
    def closure(name):
        return {name} | {v for dep in graph[name] for v in closure(dep)}
    return {isa: None if bits is None else
            [r['field'] for r in fields if r['field'] in
             {v for bit in bits for v in closure(bit)}]
            for isa, bits in policy.items()}


def generate(fields, policy):
    validate(fields, policy)
    names = [row['field'] for row in fields]
    graph = {r['field']: r.get('requires', []) for r in fields}
    def closure(name):
        return {name} | {v for dep in graph[name] for v in closure(dep)}
    lines = ['// Generated by tools/x86-isa/generate.py from feature-fields.json; do not edit.',
             '#[derive(Clone, Copy, Debug, PartialEq, Eq)]', 'pub struct Features {']
    for row in fields:
        if 'doc' in row:
            lines.extend(f'    /// {line}' for line in row['doc'].splitlines())
        lines.append(f'    pub {row["field"]}: bool,')
    lines += ['}', 'impl Features {', '    pub const NONE: Self = Self {']
    lines += [f'        {name}: false,' for name in names]
    lines += ['    };', '    /// Every declared capability, for tests and tooling; not host detection.',
              '    pub const fn all_known() -> Self { Self {']
    lines += [f'        {name}: true,' for name in names]
    lines += ['    } }', '    /// Stable schema bit IDs, covering every capability.',
              '    pub const fn fingerprint(self) -> u64 {']
    lines += [('        ' if i == 0 else '            | ') +
              (f'(self.{row["field"]} as u64)' if row["bit"] == 0 else
               f'((self.{row["field"]} as u64) << {row["bit"]})') for i, row in enumerate(fields)]
    lines += ['    }', '    pub const fn is_empty(self) -> bool { self.fingerprint() == 0 }',
              '    pub const fn contains(self, required: Self) -> bool {',
              '        self.fingerprint() & required.fingerprint() == required.fingerprint()',
              '    }', '    fn set_feature(&mut self, name: &str, enabled: bool) -> bool {',
              '        match name {']
    for row in fields:
        spellings = ' | '.join(json.dumps(s) for s in [row['field'], *row.get('aliases', [])])
        lines += [f'            {spellings} => {{', f'                self.{row["field"]} = enabled;']
        deps = closure(row['field']) - {row['field']}
        if deps:
            lines += ['                if enabled {']
            lines += [f'                    self.{dep} = true;' for dep in names if dep in deps]
            lines += ['                }']
        lines += ['            }']
    lines += ['            _ => return false,', '        }', '        true', '    }',
              "    pub fn validate(self) -> Result<(), &'static str> {"]
    for row in fields:
        for dep in row.get('requires', []):
            lines += [f'        if self.{row["field"]} && !self.{dep} {{',
                      f'            return Err("{row["field"]} requires {dep}");', '        }']
    lines += ['        Ok(())', '    }',
              "    pub fn names(self) -> impl Iterator<Item = &'static str> {", '        [']
    lines += [f'            (self.{name}, "{name}"),' for name in names]
    lines += ['        ]', '        .into_iter()',
              '        .filter_map(|(on, name)| on.then_some(name))', '    }', '}', '']
    return '\n'.join(lines)

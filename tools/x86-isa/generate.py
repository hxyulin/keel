ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT.parents[1] / 'crates/keel-asm-ir/src/x86/isa/generated.rs'
FILTERS = {'address_size', 'feature_amd', 'feature_cet', 'feature_cldemote',
           'feature_iprefetch', 'feature_knc', 'feature_lzcnt', 'feature_mpx',
           'feature_tzcnt', 'feature_ud0_compat', 'force_modrm_reg', 'force_modrm_rm',
           'mandatory_prefix', 'mode', 'modrm_mod', 'modrm_reg', 'modrm_rm',
           'operand_size', 'prefix_group1', 'rex_2', 'rex_b', 'rex_w', 'vector_length'}


def mask(value, values):
    if value is None:
        return (1 << len(values)) - 1
    inverted = str(value).startswith('!')
    number = str(value).lstrip('!')
    if number not in values:
        raise ValueError(f'unsupported filter {value}')
    bit = 1 << values.index(number)
    return ((1 << len(values)) - 1) ^ bit if inverted else bit


def generate(data):
    lines = ['// Generated by tools/x86-isa/generate.py; do not edit.',
             '// Zydis instruction data, MIT; see tools/x86-isa/LICENSE-ZYDIS.',
             'use super::{IsaForm, IsaOperand};', '#[rustfmt::skip]',
             'pub static FORMS: &[IsaForm] = &[']
    decode_keys = []
    for row in sorted(data, key=lambda r: r['mnemonic']):
        f = row.get('filters', {})
        if set(f) - FILTERS:
            raise ValueError(f'unsupported filters: {set(f) - FILTERS}')
        domains = {'mode': {'64'}, 'modrm_mod': {'3', '!3'}, 'rex_w': {'0', '1'},
                   'rex_b': {'0', '1'}, 'vector_length': {'128', '256'},
                   'prefix_group1': {'0', '1'}, 'force_modrm_reg': {True}, 'force_modrm_rm': {True}}
        domains.update({key: {'0', '1'} for key in FILTERS if key.startswith('feature_')})
        for key, domain in domains.items():
            if key in f and f[key] not in domain:
                raise ValueError(f'unsupported {key} value: {f[key]}')
        # Keep the full input snapshot, but explicitly exclude unsupported CPU
        # interpretation switches and REX2. They are not baseline long mode.
        if exclusion_reasons(row):
            continue
        operands = []
        for operand in row.get('operands', []):
            if not operand.get('visible', True):
                continue
            vals = [json.dumps(operand.get(k, '')) for k in ('operand_type', 'encoding', 'register')]
            widths = [operand.get('width' + str(size), 0) for size in (16, 32, 64)]
            operands.append('IsaOperand { kind: %s, encoding: %s, register: %s, widths: %s }' % (*vals, widths))
        mod = f.get('modrm_mod')
        has_mod = mod is not None or any(o.get('encoding', '').startswith('modrm_') for o in row.get('operands', []))
        prefix = {'none': 0, 'ignore': -1, '!f3': -2, '66': 102, 'f2': 242, 'f3': 243}[f.get('mandatory_prefix', 'ignore')]
        flags = row.get('flags', [])
        prefixes = row.get('prefix_flags', [])
        attrs = {
            'mnemonic': row['mnemonic'], 'vex': row.get('encoding') == 'vex',
            'map': {None: 0, '0f': 1, '0f38': 2, '0f3a': 3}[row.get('opcode_map')],
            'byte': int(row['opcode'], 16), 'prefix': prefix,
            'sizes': mask(f.get('operand_size'), ['16', '32', '64']),
            'addresses': mask(f.get('address_size'), ['16', '32', '64']) & 6,
            'osz': row.get('opsize_map', 'default'),
            'mod_mask': mask(mod, ['0', '1', '2', '3']) if has_mod else 0,
            'reg_mask': mask(f.get('modrm_reg'), list('01234567')),
            'rm_mask': mask(f.get('modrm_rm'), list('01234567')),
            'w': int(f.get('rex_w', -1)), 'b': int(f.get('rex_b', -1)),
            'vector': int(f.get('vector_length', 0)),
            'lock': 'accepts_lock' in prefixes,
            'rep': any(p in prefixes for p in ('accepts_rep', 'accepts_reperepz')),
            'repne': 'accepts_repnerepnz' in prefixes,
            'gather': 'is_gather' in flags, 'ignore_mod': 'ignore_modrm_mod' in flags,
            'far': 'far_branch' in flags, 'decode': f.get('feature_ud0_compat') != '1',
            'group1': int(f.get('prefix_group1', -1)),
            'isa': row['meta_info']['isa_set'], 'extension': row['meta_info']['extension'],
        }
        fields = [f'{key}: {json.dumps(value)}' for key, value in attrs.items()]
        cpl = row.get('cpl')
        if cpl is not None and (not isinstance(cpl, int) or not 0 <= cpl <= 3):
            raise ValueError(f'invalid CPL: {cpl}')
        fields.append('cpl: ' + ('None' if cpl is None else f'Some({cpl})'))
        fields.append('operands: &[' + ', '.join(operands) + ']')
        lines.append('IsaForm { ' + ', '.join(fields) + ' },')
        decode_keys.append(int(attrs['vex']) * 1024 + attrs['map'] * 256 + attrs['byte'])
    lines.append('];')
    # FORMS remains sorted by mnemonic for encoding; decoding uses this index
    # to avoid scanning the entire ISA catalogue at every instruction boundary.
    ordered = sorted((key, index) for index, key in enumerate(decode_keys))
    ranges = []
    position = 0
    for key in range(2048):
        start = position
        while position < len(ordered) and ordered[position][0] == key:
            position += 1
        ranges.append((start, position))
    assert position == len(ordered) < 65536
    lines += ['#[rustfmt::skip]', 'pub(super) static DECODE_ORDER: &[u16] = &[',
              ','.join(str(index) for _, index in ordered), '];',
              '#[rustfmt::skip]', 'pub(super) static DECODE_RANGES: &[(u16,u16)] = &[',
              ','.join(f'({start},{end})' for start, end in ranges), '];', '']
    return '\n'.join(lines)


def exclusion_reasons(row):
    f = row.get('filters', {})
    reasons = [key for key in ('feature_amd', 'feature_knc', 'feature_mpx') if f.get(key) == '1']
    if f.get('rex_2') not in (None, 'no_rex2'):
        reasons.append('rex_2')
    return reasons


def enabled(row):
    return not exclusion_reasons(row)


def opcode_identities(name, rows):
    """Generate stable public names from the explicit exposure policy."""
    variants = [row['variant'] for row in rows]
    spellings = [s for row in rows for s in [row['mnemonic'], *row.get('aliases', [])]]
    if len(set(variants)) != len(variants) or len(set(spellings)) != len(spellings):
        raise ValueError(f'duplicate {name} identity or spelling')
    lines = ['// Generated by tools/x86-isa/generate.py; do not edit.',
             '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
             f'pub enum {name} {{', *[f'    {v},' for v in variants], '}',
             f'impl {name} {{', "    pub const ALL: &'static [Self] = &[",
             *[f'        Self::{v},' for v in variants], '    ];',
             '    pub fn parse(name: &str) -> Option<Self> {', '        Some(match name {']
    for row in rows:
        for spelling in [row['mnemonic'], *row.get('aliases', [])]:
            lines.append(f'            {json.dumps(spelling)} => Self::{row["variant"]},')
    lines += ['            _ => return None,', '        })', '    }',
              "    pub const fn mnemonic(self) -> &'static str {", '        match self {']
    lines += [f'            Self::{r["variant"]} => {json.dumps(r["mnemonic"])},' for r in rows]
    lines += ['        }', '    }']
    if any('scalar_suffix' in row for row in rows):
        lines += ['    pub const fn scalar_suffix(self) -> bool {', '        match self {']
        lines += [f'            Self::{r["variant"]} => {str(r["scalar_suffix"]).lower()},' for r in rows]
        lines += ['        }', '    }']
    return '\n'.join(lines + ['}', ''])


def extension_adapters(data, mnemonics):
    identities, features, vex = [], [], []
    for mnemonic in mnemonics:
        rows = [r for r in data if enabled(r) and r['mnemonic'] == mnemonic]
        if not rows:
            raise ValueError(f'no imported forms for {mnemonic}')
        variant = mnemonic[0].upper() + mnemonic[1:]
        opcode = f'Opcode::Extension(ExtensionOpcode::{variant})'
        kinds = {o['operand_type'] for r in rows for o in r.get('operands', [])
                 if o.get('visible', True)}
        scalar = bool(kinds & {'gpr32', 'gpr64'}) and kinds <= {'gpr32', 'gpr64', 'mem'}
        identities.append(dict(variant=variant, mnemonic=mnemonic, scalar_suffix=scalar))
        features.append(dict(opcode=opcode, source_mnemonic=mnemonic))
        if any(r.get('encoding') == 'vex' for r in rows):
            vex.append(dict(opcode=opcode, source_mnemonic=mnemonic, force_w=False))
    return identities, features, vex


def form_isa(row):
    # The source labels the XMM VEX PCLMUL form simply AVX. Its independent
    # PCLMULQDQ capability must remain part of the public feature contract.
    isa = row['meta_info']['isa_set']
    return 'AVX_PCLMULQDQ' if row['mnemonic'] == 'vpclmulqdq' and isa == 'AVX' else isa


def v2_adapters(data, adapters):
    lines = ['// Generated from the shared ISA input; do not edit.',
             'use crate::x86::{V2Form, V2Opcode, V2Spec};',
             '#[rustfmt::skip]', 'pub fn spec(op: V2Opcode) -> V2Spec { match op {']
    families = {'AES': 'aes', 'SSE3': 'sse3', 'SSE3X87': 'sse3', 'SSSE3': 'ssse3',
                'SSSE3MMX': 'ssse3', 'SSE4': 'sse41', 'SSE42': 'sse42',
                'CMPXCHG16B': 'cx16', 'LAHF': 'lahf_sahf'}
    for adapter in adapters:
        rows = [r for r in data if enabled(r) and not r.get('encoding') and r['mnemonic'] == adapter['source_mnemonic']]
        if adapter['form'] == 'Fisttp':
            row = rows[0]
            prefix = map_ = byte = memory = 0
        else:
            rows = [r for r in rows if all(r.get(k) == v for k, v in adapter['selector'].items())]
            assert rows, adapter
            # The API describes the XMM form; MMX availability is separate.
            row = max(rows, key=lambda r: (r.get('filters', {}).get('mandatory_prefix') == '66',
                                           any(o['operand_type'] == 'mem' for o in r.get('operands', []))))
            prefix = {'66': 102, 'f2': 242, 'f3': 243}.get(row.get('filters', {}).get('mandatory_prefix'), 0)
            map_ = {None: 0, '0f': 15, '0f38': 56, '0f3a': 58}[row.get('opcode_map')]
            byte = int(row['opcode'], 16)
            memories = [o for o in row.get('operands', []) if o['operand_type'] == 'mem' and o.get('visible', True)]
            memory = memories[0].get('width32', 0) * 8 if memories else 0
            if adapter['form'] in ('Crc32', 'Nullary'):
                memory = 0
        family = families[row['meta_info']['isa_set']]
        assert memory == adapter['memory_bits'], (adapter, memory)
        assert family == adapter['family'], (adapter, family)
        lines.append('V2Opcode::%s => V2Spec { mnemonic: %s, family: %s, prefix: %d, map: %d, byte: %d, memory_bits: %d, form: V2Form::%s },' % (
            adapter['variant'], json.dumps(adapter['mnemonic']), json.dumps(family), prefix, map_, byte, memory, adapter['form']))
    return '\n'.join(lines + ['} }', ''])


def v3_adapters(data, adapters):
    lines = ['// Generated from the shared ISA input; do not edit.',
             'use crate::x86::{ExtensionOpcode, Opcode, V3Form, V3Opcode, V3Operand};',
             '#[rustfmt::skip]', 'pub const V3_FORMS: &[V3Form] = &[']
    seen = set()
    for adapter in adapters:
        rows = [r for r in data if enabled(r) and r.get('encoding') == 'vex' and r['mnemonic'] == adapter['source_mnemonic']]
        assert rows, adapter
        for row in rows:
            f = row.get('filters', {})
            source_operands = [o for o in row.get('operands', []) if o.get('visible', True)]
            variable = any(o['operand_type'] in ('gpr16_32_64', 'gpr32_32_64', 'gpr16_32_32') for o in source_operands)
            choices = [int(f['rex_w'])] if 'rex_w' in f else [0, 1] if variable else [0]
            for w in choices:
                if row['mnemonic'].startswith('vpcmp') and row['mnemonic'][-5:-1] in ('estr', 'istr') and bool(w) != adapter['force_w']:
                    continue
                operands = []
                roles = {'field': -1, 'source': -1, 'rm': -1, 'imm': -1}
                vsib = 0
                valid = True
                imm_reg = False
                for index, operand in enumerate(source_operands):
                    kind, encoding = operand['operand_type'], operand.get('encoding')
                    if kind in ('xmm', 'ymm', 'gpr32', 'gpr64', 'imm'):
                        code = {'xmm': 'X', 'ymm': 'Y', 'gpr32': 'D', 'gpr64': 'Q', 'imm': 'I'}[kind]
                    elif kind in ('gpr16_32_64', 'gpr32_32_64'):
                        code = 'Q' if w else 'D'
                    elif kind in ('mem', 'mem_vsibx', 'mem_vsiby'):
                        code = f'M({operand.get("width64" if w else "width32", 0) * 8})'
                        if kind != 'mem':
                            vsib = 128 if kind == 'mem_vsibx' else 256
                    else:
                        valid = False
                        break
                    operands.append('V3Operand::' + code)
                    if encoding in ('modrm_reg', 'ndsndd', 'modrm_rm'):
                        roles[{'modrm_reg': 'field', 'ndsndd': 'source', 'modrm_rm': 'rm'}[encoding]] = index
                    if kind == 'imm' or encoding == 'is4':
                        roles['imm'] = index
                        imm_reg = encoding == 'is4'
                if not valid:
                    raise ValueError(f'unsupported V3 adapter {adapter}: {row}')
                isa = form_isa(row)
                digit = int(f.get('modrm_reg', 0)) if roles['field'] < 0 else 0
                pp = {'66': 1, 'f3': 2, 'f2': 3}.get(f.get('mandatory_prefix'), 0)
                map_ = {'0f': 1, '0f38': 2, '0f3a': 3}[row['opcode_map']]
                line = 'V3Form { opcode: %s, isa: %s, map: %d, pp: %d, byte: %d, l: %s, w: %s, operands: &[%s], field: %d, digit: %d, source: %d, rm: %d, imm: %d, imm_reg: %s, vsib: %d },' % (
                    adapter['opcode'], json.dumps(isa), map_, pp, int(row['opcode'], 16), str(f.get('vector_length') == '256').lower(), str(bool(w)).lower(),
                    ','.join(operands), roles['field'], digit, roles['source'], roles['rm'], roles['imm'], str(imm_reg).lower(), vsib)
                if line not in seen:
                    seen.add(line)
                    lines.append(line)
    return '\n'.join(lines + ['];', ''])


def fixed_adapters(data, adapters):
    lines = ['// Generated from the shared ISA input; do not edit.',
             'use crate::x86::FixedOpcode;', '#[rustfmt::skip]',
             "pub const fn bytes(op: FixedOpcode) -> &'static [u8] { match op {"]
    for adapter in adapters:
        candidates = []
        for row in data:
            if not enabled(row) or row.get('encoding') or row['mnemonic'] != adapter['source_mnemonic']:
                continue
            if any(o.get('visible', True) for o in row.get('operands', [])):
                continue
            f = row.get('filters', {})
            for p66 in [False, True]:
                for w in [False, True]:
                    if f.get('rex_w') is not None and int(f['rex_w']) != int(w):
                        continue
                    osz = row.get('opsize_map')
                    size = 64 if osz in ('force64', 'force32_or_64') else (16 if p66 else 64) if osz == 'default64' else (64 if w else 32) if osz in ('ignore66', 'force32_or_rexw') else 64 if w else 16 if p66 else 32
                    if adapter['size'] and size != adapter['size']:
                        continue
                    if not mask(f.get('operand_size'), ['16', '32', '64']) & {16: 1, 32: 2, 64: 4}[size]:
                        continue
                    out = [0x9b] if adapter['wait'] else []
                    prefix = {'66': 102, 'f2': 242, 'f3': 243}.get(f.get('mandatory_prefix'), 0)
                    if p66 and prefix != 102:
                        out.append(102)
                    if prefix:
                        out.append(prefix)
                    if w:
                        out.append(0x48)
                    out.extend({None: [], '0f': [15], '0f38': [15, 56], '0f3a': [15, 58]}[row.get('opcode_map')])
                    out.append(int(row['opcode'], 16))
                    if 'modrm_mod' in f:
                        if f['modrm_mod'] != '3':
                            continue
                        out.append(0xc0 | int(f['modrm_reg']) << 3 | int(f['modrm_rm']))
                    candidates.append(out)
        if not candidates:
            raise ValueError(f'no fixed encoding for {adapter}')
        result = min(candidates, key=len)
        lines.append(f'FixedOpcode::{adapter["variant"]} => &{result},')
    lines += ['} }', '#[rustfmt::skip]',
              "pub const fn source(op: FixedOpcode) -> (&'static str, Option<u16>, bool) { match op {"]
    for adapter in adapters:
        size = 'None' if adapter['size'] is None else f'Some({adapter["size"]})'
        lines.append(f'FixedOpcode::{adapter["variant"]} => ({json.dumps(adapter["source_mnemonic"])}, {size}, {str(adapter["wait"]).lower()}),')
    lines += ['} }', '#[rustfmt::skip]',
              "pub fn fixed_width_mnemonic(source: &str, size: u16) -> Option<&'static str> { match (source, size) {"]
    seen = set()
    for adapter in adapters:
        if adapter['size'] is None or adapter['wait']:
            continue
        key = (adapter['source_mnemonic'], adapter['size'])
        if key in seen:
            raise ValueError(f'ambiguous fixed width mnemonic: {key}')
        seen.add(key)
        lines.append(f'({json.dumps(key[0])}, {key[1]}) => Some({json.dumps(adapter["mnemonic"])}),')
    return '\n'.join(lines + ['_ => None,', '} }', ''])


def feature_adapters(data, adapters, policy):
    lines = ['// Generated ISA requirements and Keel profile policy; do not edit.',
             'use crate::x86::{CoreOpcode, ExtensionOpcode, Features, Opcode, V2Opcode, V3Opcode};',
             '#[rustfmt::skip]', 'pub fn opcode_features(op: Opcode) -> Features { match op {']
    for adapter in adapters:
        sets = {form_isa(r) for r in data if enabled(r) and r['mnemonic'] == adapter['source_mnemonic']
                and all(r.get(k) == v for k, v in adapter.get('selector', {}).items())}
        if sets - policy.keys():
            raise ValueError(f'unclassified ISA requirements for {adapter}: {sets - policy.keys()}')
        choices = [policy[name] for name in sorted(sets) if policy[name] is not None]
        bits = min(choices, key=len) if choices else []
        if bits:
            lines.append(f'{adapter["opcode"]} => Features {{ ' + ', '.join(f'{bit}: true' for bit in bits) + ', ..Features::NONE },')
    lines += ['_ => Features::NONE,', '} }', '#[rustfmt::skip]',
              'pub fn feature_policy(isa: &str) -> Features { match isa {']
    for name, bits in policy.items():
        if bits:
            lines.append(f'{json.dumps(name)} => Features {{ ' + ', '.join(f'{bit}: true' for bit in bits) + ', ..Features::NONE },')
    return '\n'.join(lines + ['_ => Features::NONE,', '} }', ''])


def documentation_inventory(v2_source, adapters):
    target = ROOT.parents[1] / 'docs/v2-coverage/inventory.json'
    inventory = json.loads(target.read_text())
    old = {row['mnemonic']: row for row in inventory['instructions']}
    rows = []
    pattern = r'V2Opcode::(\w+) => V2Spec \{ mnemonic: "([^"]+)", family: "([^"]+)", prefix: (\d+), map: (\d+), byte: (\d+), memory_bits: (\d+), form: V2Form::(\w+)'
    for variant, mnemonic, family, prefix, map_, byte, memory, form in re.findall(pattern, v2_source):
        row = old.get(mnemonic, {'operand_forms': ['xmm,xmm' + (',imm8' if form == 'Control' else ''),
                                                  'xmm,m128' + (',imm8' if form == 'Control' else '')],
                                  'implicit_operands': []})
        row.update(mnemonic=mnemonic, family=family, prefix=int(prefix), map=int(map_), byte=int(byte), memory_bits=int(memory), form=form)
        if family == 'aes':
            row['optional'] = True
            row['psabi_level'] = None
        rows.append(row)
    assert len(rows) == len(adapters)
    inventory['instructions'] = rows
    inventory['scope'] = 'legacy x86-64 XMM/GPR and SSSE3 MMX forms, plus optional AES; no VEX/YMM'
    inventory['excluded'] = [row for row in inventory['excluded'] if row['mnemonic'] != 'SSSE3 MMX forms']
    inventory['generated_encoding_fields'] = 'tools/x86-isa/generate.py; pinned Zydis source in tools/x86-isa/zydis-source.json; operand descriptions and validation notes are retained'
    if inventory['primary_inventory']['project'] == 'Intel XED':
        inventory['independent_inventory'] = inventory['primary_inventory']
    inventory['primary_inventory'] = {'project': 'Zydis instruction database',
                                     'commit': 'eaf92a02dca616b90c12b2ebc338d87ed943c84f',
                                     'file': 'datafiles/instructions.json',
                                     'provenance': 'tools/x86-isa/zydis-source.json'}
    return target, json.dumps(inventory, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--check-upstream', type=Path)
    args = parser.parse_args()
    source = (ROOT / 'zydis.json').read_bytes()
    provenance = json.loads((ROOT / 'zydis-source.json').read_text())
    if hashlib.sha256(source).hexdigest() != provenance['subset_sha256']:
        raise ValueError('Zydis subset checksum mismatch')
    data = json.loads(source)
    if args.check_upstream:
        upstream = args.check_upstream.read_bytes()
        if hashlib.sha256(upstream).hexdigest() != provenance['upstream_sha256']:
            raise ValueError('upstream Zydis checksum mismatch')
        expected = []
        for row in json.loads(upstream):
            if row.get('encoding') in (None, 'vex') and row.get('filters', {}).get('mode') != '!64':
                row.pop('comment', None)
                expected.append(row)
        if expected != data:
            raise ValueError('Zydis subset differs from upstream selection')
    data += json.loads((ROOT / 'keel-extensions.json').read_text())
    adapters = json.loads((ROOT / 'keel-adapters.json').read_text())
    policy = json.loads((ROOT / 'feature-policy.json').read_text())
    fields = json.loads((ROOT / 'feature-fields.json').read_text())
    feature_source = feature_fields.generate(fields, policy)
    identities, features, vex = extension_adapters(data, adapters['extensions'])
    outputs = {OUTPUT: generate(data), OUTPUT.with_name('v2.rs'): v2_adapters(data, adapters['v2']),
               OUTPUT.with_name('v3.rs'): v3_adapters(data, adapters['v3'] + vex),
               OUTPUT.with_name('fixed.rs'): fixed_adapters(data, adapters['fixed']),
               OUTPUT.with_name('features.rs'): feature_adapters(data, adapters['feature_opcodes'] + features, feature_fields.closed_policy(fields, policy))}
    outputs[OUTPUT.with_name('feature_fields.rs')] = feature_source
    outputs.update(cpu_profiles.outputs(ROOT, OUTPUT, fields))
    for group, name in [('v2', 'V2Opcode'), ('v3', 'V3Opcode'), ('fixed', 'FixedOpcode')]:
        outputs[OUTPUT.with_name(f'{group}_opcodes.rs')] = opcode_identities(name, adapters['identities'][group])
    outputs[OUTPUT.with_name('extension_opcodes.rs')] = opcode_identities('ExtensionOpcode', identities)
    outputs.update(api_identities.outputs(ROOT, OUTPUT, opcode_identities))
    outputs.update(registers.outputs(ROOT, OUTPUT))
    outputs.update(core_mappings.outputs(ROOT, OUTPUT))
    outputs.update(att_rules.outputs(ROOT, OUTPUT))
    outputs.update(intrinsic_registry.outputs(ROOT))
    outputs.update(system_intrinsics.outputs(ROOT, OUTPUT))

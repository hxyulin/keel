"""Global intrinsic identity allocation, independent of metadata families."""
import json
import re

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
FAMILIES = {'x86_system': 'system-intrinsics.json', 'x86_query': 'query-bindings.json'}
EFFECTS = ['None', 'Read', 'Write', 'ReadWrite', 'Barrier']


def family_variant(name):
    return ''.join(part[:1].upper() + part[1:] for part in name.split('_'))


def owned_family(owner, declaration):
    """The x86 family a metadata family assigns to its declaration."""
    return 'system' if owner == 'x86_system' else declaration['binding']['kind']


def validate(schema):
    if not isinstance(schema, dict) or set(schema) != {'intrinsics'}:
        raise ValueError('unknown or missing registry fields')
    rows = schema['intrinsics']
    if not isinstance(rows, list) or not rows:
        raise ValueError('empty intrinsic registry')
    variants, inventory = set(), set()
    required = {'id', 'variant', 'inventory', 'metadata', 'trap', 'inline'}
    optional = {'doc', 'family', 'effects'}
    for index, row in enumerate(rows):
        if not isinstance(row, dict) or not required <= row.keys() or row.keys() - required - optional:
            raise ValueError('unknown or missing registry row fields')
        if type(row['id']) is not int or row['id'] != index:
            raise ValueError('registry IDs must be contiguous and ordered from zero')
        variant = row['variant']
        if not isinstance(variant, str) or not re.fullmatch(r'[A-Z][A-Za-z0-9]*', variant) or variant in variants:
            raise ValueError('invalid or duplicate registry variant')
        variants.add(variant)
        position = row['inventory']
        if type(position) is not int or not 0 <= position < len(rows) or position in inventory:
            raise ValueError('inventory positions must be a complete permutation')
        inventory.add(position)
        if row['metadata'] not in ['handwritten', *FAMILIES]:
            raise ValueError('unknown registry metadata owner')
        if 'doc' in row and (not isinstance(row['doc'], str) or not row['doc'].strip()):
            raise ValueError('invalid registry documentation')
        if type(row['trap']) is not bool or type(row['inline']) is not bool:
            raise ValueError('trap and inline must be booleans')
        family = row.get('family')
        if (family is not None) != variant.startswith('X86'):
            raise ValueError('x86 intrinsics, and only they, name a lowering family')
        if family is not None and (not isinstance(family, str)
                                   or not re.fullmatch(r'[a-z][a-z0-9]*(?:_[a-z0-9]+)*', family)):
            raise ValueError('invalid lowering family name')
        if ('effects' in row) != (row['metadata'] == 'handwritten'):
            raise ValueError('effects belong to the metadata owner')
        if 'effects' in row and row['effects'] not in EFFECTS:
            raise ValueError('unknown memory effects')
    return rows


def bind(schema, families):
    rows = validate(schema)
    if set(families) != set(FAMILIES):
        raise ValueError('missing or unknown registry metadata families')
    bindings, names = {}, set()
    for family, declarations in families.items():
        for declaration in declarations:
            variant = declaration['variant']
            if variant in bindings or declaration['name'] in names:
                raise ValueError('duplicate family intrinsic identity')
            bindings[variant] = (family, declaration)
            names.add(declaration['name'])
    expected = {r['variant'] for r in rows if r['metadata'] != 'handwritten'}
    if bindings.keys() != expected:
        raise ValueError('registry and family membership differ')
    for row in rows:
        if row['metadata'] == 'handwritten':
            continue
        family, declaration = bindings[row['variant']]
        if family != row['metadata'] or type(declaration['id']) is not int or declaration['id'] != row['id']:
            raise ValueError('registry and family ID/owner mismatch')
        if 'doc' in row:
            raise ValueError('family owns documentation for generated metadata')
        if row.get('family') != owned_family(family, declaration):
            raise ValueError('registry and family lowering family differ')
        if declaration['memory'] not in EFFECTS:
            raise ValueError('unknown memory effects')
    return rows, bindings


def facts(schema, families):
    """(variant, effects, trap, inline, family) per row, in ID order."""
    rows, bindings = bind(schema, families)
    return [(row['variant'],
             row['effects'] if 'effects' in row else bindings[row['variant']][1]['memory'],
             row['trap'], row['inline'], row.get('family')) for row in rows]


def generate(schema, families):
    rows, bindings = bind(schema, families)
    lines = [HEADER, '// IDs and ALL positions are separate compatibility contracts.',
             'use crate::MemoryEffects;', '',
             '#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]', 'pub enum Intrinsic {']
    for row in rows:
        doc = bindings[row['variant']][1]['doc'] if row['variant'] in bindings else row.get('doc')
        if doc:
            lines += [f'    #[doc = {json.dumps(doc, ensure_ascii=False)}]']
        lines += [f'    {row["variant"]} = {row["id"]},']
    lines += ['}', '', 'impl Intrinsic {', f'    pub const ALL: [Intrinsic; {len(rows)}] = [']
    lines += [f'        Intrinsic::{r["variant"]},' for r in sorted(rows, key=lambda r: r['inventory'])]
    lines += ['    ];', '}', '',
              '/// Generated x86-only patterns keep portable intrinsic matches exhaustive.',
              '#[doc(hidden)]', '#[macro_export]', 'macro_rules! x86_intrinsics {',
              '    () => {']
    x86 = [row['variant'] for row in rows if row['variant'].startswith('X86')]
    lines += [f'        {"" if index == 0 else "    | "}$crate::Intrinsic::{variant}'
              for index, variant in enumerate(x86)]
    lines += ['    };', '}', '']
    return '\n'.join(lines + fact_table(facts(schema, families)))


def fact_table(rows):
    names = sorted({family for *_, family in rows if family is not None})
    lines = ['/// The backend module group that validates and lowers an x86 intrinsic.',
             '#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]', 'pub enum X86Family {']
    lines += [f'    {family_variant(name)},' for name in names]
    lines += ['}', '', 'struct Facts {', '    effects: MemoryEffects,', '    may_trap: bool,',
              '    inlineable: bool,', '    x86_family: Option<X86Family>,', '}', '',
              'const fn f(',
              '    effects: MemoryEffects,', '    may_trap: bool,', '    inlineable: bool,',
              '    x86_family: Option<X86Family>,', ') -> Facts {', '    Facts {', '        effects,',
              '        may_trap,', '        inlineable,', '        x86_family,', '    }', '}', '',
              'use MemoryEffects as M;', 'use X86Family as F;', '',
              '/// Indexed by intrinsic ID.', '#[rustfmt::skip]',
              f'static FACTS: [Facts; {len(rows)}] = [']
    for variant, effects, trap, inline, family in rows:
        family = 'None' if family is None else f'Some(F::{family_variant(family)})'
        lines += [f'    f(M::{effects}, {str(trap).lower()}, {str(inline).lower()}, {family}), // {variant}']
    lines += ['];', '', 'impl Intrinsic {',
              '    /// The memory the intrinsic may access, by the rules of [`MemoryEffects`].',
              '    #[inline]', '    pub fn memory_effects(self) -> MemoryEffects {',
              '        FACTS[self as usize].effects', '    }', '',
              '    /// Whether the intrinsic may fault, trap or exit exceptionally.',
              '    #[inline]', '    pub fn may_trap(self) -> bool {',
              '        FACTS[self as usize].may_trap', '    }', '',
              '    /// Whether the inliner may copy the intrinsic into another function.',
              '    #[inline]', '    pub fn inlineable(self) -> bool {',
              '        FACTS[self as usize].inlineable', '    }', '',
              '    /// The x86 lowering family; `None` exactly for portable intrinsics.',
              '    #[inline]', '    pub fn x86_family(self) -> Option<X86Family> {',
              '        FACTS[self as usize].x86_family', '    }', '}', '']
    return lines


def outputs(root):
    schema = json.loads((root / 'intrinsic-registry.json').read_text())
    families = {family: json.loads((root / file).read_text())['intrinsics']
                for family, file in FAMILIES.items()}
    return {root.parents[1] / 'crates/keel-ir/src/generated/intrinsic_registry.rs':
            generate(schema, families)}

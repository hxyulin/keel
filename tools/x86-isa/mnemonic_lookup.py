"""Generate mnemonic hashing and private opcode-to-form-group dispatch."""
from collections import defaultdict
import itertools
import json
import re

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
MASK64 = (1 << 64) - 1


def groups(data):
    result = []
    position = 0
    for name, rows in itertools.groupby(sorted(data, key=lambda r: r['mnemonic']),
                                        key=lambda r: r['mnemonic']):
        count = sum(1 for _ in rows)
        if not name or not name.isascii() or position + count > 65535:
            raise ValueError('mnemonic groups require ASCII names and u16 form indices')
        result.append((name, position, count))
        position += count
    if not result:
        raise ValueError('empty mnemonic catalogue')
    return result


def name_hash(name):
    value = 0xcbf29ce484222325
    for byte in name.encode('ascii'):
        value = ((value ^ byte) * 0x100000001b3) & MASK64
    return value ^ (value >> 32)


def perfect_hash(entries):
    slot_count = 1 << ((3 * len(entries) + 1) // 2 - 1).bit_length()
    bucket_count = 1 << ((len(entries) + 2) // 3 - 1).bit_length()
    if slot_count > 32768:
        raise ValueError('mnemonic hash exceeds u16 singleton slot capacity')
    buckets = defaultdict(list)
    for name, start, count in entries:
        value = name_hash(name)
        buckets[value & (bucket_count - 1)].append((value, start, count))
    slots = [None] * slot_count
    displacements = [0] * bucket_count
    bits = bucket_count.bit_length() - 1
    for bucket, rows in sorted(buckets.items(), key=lambda x: (-len(x[1]), x[0])):
        if len(rows) == 1:
            continue
        for displacement in range(32768):
            targets = [((h >> 32) + displacement * ((h >> bits) | 1)) & (slot_count - 1)
                       for h, _, _ in rows]
            if len(set(targets)) == len(rows) and all(slots[t] is None for t in targets):
                break
        else:
            raise ValueError('no mnemonic displacement found; increase hash capacity')
        displacements[bucket] = displacement
        for target, (_, start, count) in zip(targets, rows):
            slots[target] = (start, count)
    for bucket, rows in sorted(buckets.items()):
        if len(rows) != 1:
            continue
        target = slots.index(None)
        _, start, count = rows[0]
        slots[target] = (start, count)
        displacements[bucket] = 32768 | target
    return displacements, slots


def hash_source(entries):
    displacements, slots = perfect_hash(entries)
    lines = [HEADER, 'use super::{FORMS, IsaForm};', '#[rustfmt::skip]',
             f'const DISPLACEMENTS: [u16; {len(displacements)}] = [']
    lines += [','.join(map(str, displacements[i:i + 16])) + ','
              for i in range(0, len(displacements), 16)]
    lines += ['];', '#[rustfmt::skip]', f'const RANGES: [(u16,u16); {len(slots)}] = [']
    lines += [','.join(f'({a},{n})' for a, n in [v or (0, 0) for v in slots[i:i + 8]]) + ','
              for i in range(0, len(slots), 8)]
    lines += ['];', '#[inline]',
              "pub(super) fn forms(name: &str) -> &'static [IsaForm] {",
              f'    if !({min(len(w) for w, _, _ in entries)}..={max(len(w) for w, _, _ in entries)}).contains(&name.len()) {{ return &[]; }}',
              '    let mut hash = 0xcbf29ce484222325u64;',
              '    for byte in name.bytes() { hash = (hash ^ u64::from(byte)).wrapping_mul(0x100000001b3); }',
              '    hash ^= hash >> 32;',
              f'    let displacement = DISPLACEMENTS[hash as usize & {len(displacements) - 1}];',
              '    let slot = if displacement & 32768 != 0 {',
              '        usize::from(displacement & 32767)',
              '    } else {',
              f'        ((hash >> 32).wrapping_add(u64::from(displacement).wrapping_mul((hash >> {len(displacements).bit_length() - 1}) | 1)) as usize) & {len(slots) - 1}',
              '    };',
              '    let (start, count) = RANGES[slot];',
              '    let start = usize::from(start);',
              '    if count != 0 && FORMS[start].mnemonic == name {',
              '        &FORMS[start..start + usize::from(count)]',
              '    } else { &[] }', '}', '']
    # Generated code stays byte-stable under cargo fmt.
    lines.insert(lines.index('#[inline]'), '#[rustfmt::skip]')
    return '\n'.join(lines)


def canonical_name(name, conditions):
    """The static-name subset of the encoder's dialect normalization.

    Generated Rust tests compare every emitted case with the actual normalizer.
    Operand-dependent and payload-dependent cases deliberately use the fallback.
    """
    name = name.split('.')[0]
    if name in ('pushw', 'popw'):
        name = name[:-1]
    if name in ('movabs', 'movabs32'):
        name = 'mov'
    if name.endswith('64') and name.startswith(('pcmp', 'vpcmp')):
        name = name[:-2]
    if name in ('fstcw', 'fstsw', 'fstenv', 'fsave'):
        name = 'fn' + name[1:]
    match = re.fullmatch(r'cmp(?:eq|lt|le|unord|neq|nlt|nle|ord)(ps|pd|ss|sd)', name)
    if match:
        name = 'cmp' + match[1]
    name = {'callf': 'call', 'jmpf': 'jmp', 'xlatb': 'xlat', 'sal': 'shl'}.get(name, name)
    for stem in ('cmov', 'set', 'j'):
        if name.startswith(stem):
            name = stem + conditions.get(name[len(stem):], name[len(stem):])
            break
    return name


def opcode_groups(entries, identities, core, adapters, extensions, conditions):
    ranges = {name: (start, count) for name, start, count in entries}
    aliases = {alias: row['isa_name'] for row in conditions for alias in row['aliases']}
    result = {}

    def add(pattern, name):
        name = canonical_name(name, aliases)
        if name not in ranges:
            raise ValueError(f'no mnemonic group for {pattern}: {name}')
        if pattern in result and result[pattern] != ranges[name]:
            raise ValueError(f'conflicting mnemonic groups for {pattern}')
        result[pattern] = ranges[name]

    for row in identities['baseline']:
        if 'mnemonic' in row:
            add('Opcode::' + row['variant'], row['mnemonic'])
    for row in identities['x87']:
        add(f'Opcode::X87(X87Opcode::{row["variant"]})', row['mnemonic'])
    for row in core:
        if 'mnemonic' in row and row['variant'] != 'Int':
            add(f'Opcode::Core(CoreOpcode::{row["variant"]})', row['mnemonic'])
    for family, ty, rows in [('V2', 'V2Opcode', adapters['v2']),
                             ('V3', 'V3Opcode', adapters['identities']['v3']),
                             ('Fixed', 'FixedOpcode', adapters['fixed']),
                             ('Extension', 'ExtensionOpcode', extensions)]:
        for row in rows:
            name = row['source_mnemonic'] if family == 'Fixed' else row['mnemonic']
            add(f'Opcode::{family}({ty}::{row["variant"]})', name)
    for family, stem in [('Jcc', 'j'), ('Setcc', 'set'), ('Cmovcc', 'cmov')]:
        for row in conditions:
            add(f'Opcode::{family}({row["code"]})', stem + row['isa_name'])
    return result


def dispatch_source(mapping):
    ranges = sorted(set(mapping.values()))
    ids = {pair: index for index, pair in enumerate(ranges)}
    if len(ranges) > 65535:
        raise ValueError('opcode groups exceed u16 capacity')
    lines = [HEADER,
             'use keel_asm_ir::x86::{',
             '    CoreOpcode, ExtensionOpcode, FixedOpcode, Opcode, V2Opcode, V3Opcode, X87Opcode,',
             '    isa::{self, IsaForm},', '};',
             '#[rustfmt::skip]', 'const RANGES: &[(u16,u16)] = &[',
             *[f'({a},{n}),' for a, n in ranges], '];', '#[rustfmt::skip]',
             "pub(super) fn forms(opcode: Opcode, name: &str) -> &'static [IsaForm] {",
             '    let group: u16 = match opcode {']
    lines += [f'        {pattern} => {ids[pair]},' for pattern, pair in sorted(mapping.items())]
    lines += ['        _ => return isa::forms(name),', '    };',
              '    let (start, count) = RANGES[usize::from(group)];',
              '    let start = usize::from(start);',
              '    debug_assert_eq!(isa::FORMS[start].mnemonic, name, "regenerate opcode mnemonic groups");',
              '    &isa::FORMS[start..start + usize::from(count)]', '}',
              '#[cfg(test)]', '#[rustfmt::skip]', 'pub(super) const CASES: &[Opcode] = &[',
              *[f'    {pattern},' for pattern in sorted(mapping)], '];', '']
    return '\n'.join(lines)


def outputs(root, output, data, adapters, extensions):
    entries = groups(data)
    mapping = opcode_groups(entries, json.loads((root / 'api-identities.json').read_text()),
                            json.loads((root / 'core-identities.json').read_text()),
                            adapters, extensions,
                            json.loads((root / 'condition-codes.json').read_text()))
    assembler = root.parents[1] / 'crates/keel-asm/src/x86/encode/mnemonics.rs'
    return {output.with_name('mnemonic_index.rs'): hash_source(entries),
            assembler: dispatch_source(mapping)}

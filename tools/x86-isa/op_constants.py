"""Generate `x86::op`: one typed constant per static payload-table mnemonic.

Baseline unit variants such as `Opcode::Mov` already name themselves, so the
module covers only identities behind a payload enum. Spellings follow the
order of `Opcode::parse`; a name an earlier table claims gets no constant.
The generated `ALL` table lets a Rust test compare every constant with the
parser, including the handwritten Core grammar this module cannot see.
"""
import json
import re

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'


def const_name(mnemonic):
    name = mnemonic.upper().replace('.', '_')
    if not re.fullmatch(r'[A-Z][A-Z0-9_]*', name):
        raise ValueError(f'mnemonic {mnemonic!r} has no constant name')
    return name


def tables(identities, core, adapters, extensions, conditions):
    """Yield (spellings, canonical mnemonic or None, Rust expression) in parse order."""
    for row in identities['baseline']:
        yield row.get('spellings', []), None, None
    for row in core:
        if 'mnemonic' in row:
            yield row['spellings'], row['mnemonic'], f'Opcode::Core(CoreOpcode::{row["variant"]})'
    groups = [('X87', 'X87Opcode', identities['x87']),
              ('Fixed', 'FixedOpcode', adapters['identities']['fixed']),
              ('Extension', 'ExtensionOpcode', extensions),
              ('V3', 'V3Opcode', adapters['identities']['v3'])]
    for family, ty, rows in groups:
        for row in rows:
            spellings = [row['mnemonic'], *row.get('aliases', [])]
            if family == 'Fixed' and row['mnemonic'] == 'fwait':
                spellings.append('wait')
            yield spellings, row['mnemonic'], f'Opcode::{family}({ty}::{row["variant"]})'
    for row in identities['evex']:
        yield [row['mnemonic']], row['mnemonic'], \
            f'Opcode::Evex(EvexOpcode::new(EvexMnemonic::{row["variant"]}))'
    yield ['pclmulqdq'], None, None
    for row in adapters['identities']['v2']:
        yield [row['mnemonic'], *row.get('aliases', [])], row['mnemonic'], \
            f'Opcode::V2(V2Opcode::{row["variant"]})'
    for family, stem in [('Jcc', 'j'), ('Setcc', 'set'), ('Cmovcc', 'cmov')]:
        for row in conditions:
            yield [stem + alias for alias in row['aliases']], stem + row['name'], \
                f'Opcode::{family}({row["code"]})'


def constants(rows):
    claimed, names, result = set(), set(), []
    for spellings, mnemonic, expression in rows:
        if mnemonic is not None and mnemonic not in claimed:
            name = const_name(mnemonic)
            if name in names:
                raise ValueError(f'duplicate x86 opcode constant {name}')
            names.add(name)
            result.append((name, mnemonic, expression))
        claimed.update(spellings)
    return result


def source(entries):
    lines = [HEADER, 'use super::*;']
    lines += [f'pub const {name}: Opcode = {expression};' for name, _, expression in entries]
    lines += ['/// Every constant with the spelling `Opcode::parse` maps to it.',
              '#[rustfmt::skip]', "pub const ALL: &[(&str, Opcode)] = &["]
    lines += [f'    ({json.dumps(mnemonic)}, {name}),' for name, mnemonic, _ in entries]
    return '\n'.join(lines + ['];', ''])


def outputs(root, output, adapters, extensions):
    rows = tables(json.loads((root / 'api-identities.json').read_text()),
                  json.loads((root / 'core-identities.json').read_text()),
                  adapters, extensions,
                  json.loads((root / 'condition-codes.json').read_text()))
    return {output.with_name('op.rs'): source(constants(rows))}

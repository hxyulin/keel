#!/usr/bin/env python3
"""Prove a bounded XED-to-Rust table import; this is not an x86 decoder."""

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def records(source):
    """Preserve repeated PATTERN/OPERANDS pairs within each XED record."""
    result = []
    for block in re.findall(r"^\{\s*\n(.*?)^\}", source, re.M | re.S):
        metadata = {}
        forms = []
        pending = None
        for line in block.splitlines():
            match = re.match(r"^([A-Z_]+)\s*:\s*(.*)$", line)
            if not match:
                if line.strip() and not line.lstrip().startswith("#"):
                    raise ValueError(f"unsupported record line: {line}")
                continue
            key, value = match.groups()
            value = value.strip()
            if key == "PATTERN":
                if pending is not None:
                    raise ValueError("PATTERN without OPERANDS")
                pending = value
            elif key == "OPERANDS":
                if pending is None:
                    raise ValueError("OPERANDS without PATTERN")
                forms.append({"pattern": pending, "operands": value})
                pending = None
            else:
                if key in metadata:
                    raise ValueError(f"duplicate metadata: {key}")
                metadata[key] = value
        if pending is not None or not forms or "ICLASS" not in metadata:
            raise ValueError("incomplete XED record")
        for form in forms:
            result.append({"metadata": metadata.copy(), **form})
    if not result:
        raise ValueError("no XED records")
    return result


def normalize(record):
    tokens = record["pattern"].split()
    if "not64" in tokens:
        return None
    opcode = []
    while tokens and re.fullmatch(r"0x[0-9A-Fa-f]{2}", tokens[0]):
        opcode.append(int(tokens.pop(0), 16))
    if not opcode:
        raise ValueError("missing literal opcode")
    form = {
        "mnemonic": record["metadata"]["ICLASS"].lower(),
        "opcode": opcode,
        "mod_mask": 0,
        "reg": None,
        "rm": None,
        "force64": False,
        "no_rex2": False,
        "operands": record["operands"],
        "metadata": record["metadata"],
        "pattern": record["pattern"],
    }
    has_modrm = False
    for token in tokens:
        if token == "MOD[mm]":
            form["mod_mask"] = 15
        elif token == "MOD[0b11]":
            form["mod_mask"] = 8
        elif token == "MOD!=3":
            form["mod_mask"] &= 7
        elif token == "MOD=3":
            form["mod_mask"] &= 8
        elif token == "FORCE64()":
            form["force64"] = True
        elif token == "norex2_prefix":
            form["no_rex2"] = True
        elif token == "MODRM()":
            has_modrm = True
        elif token in ("RM[nnn]", "mode64"):
            pass
        elif match := re.fullmatch(r"(REG|RM)\[0b([01]{3})\]", token):
            form["reg" if match[1] == "REG" else "rm"] = int(match[2], 2)
        else:
            raise ValueError(f"unsupported predicate: {token}")
    if has_modrm and not form["mod_mask"]:
        raise ValueError("MODRM without a MOD domain")
    if not form["mod_mask"] and (form["reg"] is not None or form["rm"] is not None):
        raise ValueError("ModRM constraint without a MOD domain")
    return form


def catalog(source):
    imported, excluded, unsupported = [], [], []
    for record in records(source):
        try:
            form = normalize(record)
        except ValueError as error:
            unsupported.append({**record, "reason": str(error)})
            continue
        if form is None:
            excluded.append(record)
        else:
            imported.append(form)
    return {"forms": imported, "excluded_non_long_mode": excluded, "unsupported": unsupported}


def candidates(forms, opcode, modrm=None):
    """Match opcode/group constraints only, without consuming instruction bytes.

    Prefix legality, operand extraction and instruction length belong to the
    future decoder. Return every candidate rather than hide ambiguous matches.
    """
    result = []
    for form in forms:
        if form["opcode"] != list(opcode):
            continue
        if form["mod_mask"]:
            if modrm is None or not (form["mod_mask"] & (1 << (modrm >> 6))):
                continue
            if form["reg"] is not None and (modrm >> 3) & 7 != form["reg"]:
                continue
            if form["rm"] is not None and modrm & 7 != form["rm"]:
                continue
        elif modrm is not None:
            continue
        result.append(form)
    return result


def rust_table(forms):
    lines = [
        "// Generated by tools/x86-isa/probe.py. Experimental opcode dispatch only.",
        "// Intel XED-derived encoding data: Apache-2.0; see system-xed.txt.",
        "#[derive(Debug)]",
        "pub struct Form {",
        "    pub mnemonic: &'static str, pub opcode: &'static [u8],",
        "    pub mod_mask: u8, pub reg: Option<u8>, pub rm: Option<u8>,",
        "    pub force64: bool, pub no_rex2: bool,",
        "    pub operands: &'static str,",
        "}",
        "pub static FORMS: &[Form] = &[",
    ]
    for form in forms:
        option = lambda value: "None" if value is None else f"Some({value})"
        lines.append(
            "    Form { "
            f'mnemonic: {json.dumps(form["mnemonic"])}, opcode: &{form["opcode"]}, '
            f'mod_mask: {form["mod_mask"]}, reg: {option(form["reg"])}, '
            f'rm: {option(form["rm"])}, force64: {str(form["force64"]).lower()}, '
            f'no_rex2: {str(form["no_rex2"]).lower()}, '
            f'operands: {json.dumps(form["operands"])}' + " },"
        )
    return "\n".join(lines + ["];", ""])


def load():
    provenance = json.loads((ROOT / "source.json").read_text())
    data = (ROOT / "system-xed.txt").read_bytes()
    if hashlib.sha256(data).hexdigest() != provenance["subset_sha256"]:
        raise ValueError("checked-in XED subset checksum mismatch")
    return provenance, data.decode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emit-rust", action="store_true")
    parser.add_argument("--check-upstream", type=Path, help="verify against the exact pinned upstream file")
    args = parser.parse_args()
    provenance, source = load()
    if args.check_upstream:
        upstream = args.check_upstream.read_bytes()
        if hashlib.sha256(upstream).hexdigest() != provenance["upstream_sha256"]:
            raise ValueError("upstream checksum mismatch")
        selected = []
        for block in re.finditer(r"^\{\s*\n(.*?)^\}", upstream.decode(), re.M | re.S):
            name = re.search(r"^ICLASS\s*:\s*(\S+)", block.group(), re.M)
            if name and name[1] in provenance["selection"]:
                selected.append(block.group())
        expected = records("\n".join(selected))
        if records(source) != expected:
            raise ValueError("subset differs from upstream selection")
    report = catalog(source)
    if args.emit_rust:
        print(rust_table(report["forms"]), end="")
    else:
        print(json.dumps({"source": provenance, **report}, indent=2))


if __name__ == "__main__":
    main()

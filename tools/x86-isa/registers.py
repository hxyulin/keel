"""Generate x86 register API/data mappings. Instruction and privilege rules stay separate."""
import json
import re

DIMS = ['number', 'width', 'high_byte']
HEADER = '// Generated by tools/x86-isa/generate.py from registers.json; do not edit.'


def known_keys(value, allowed, label):
    if not isinstance(value, dict) or set(value) - set(allowed.split()):
        raise ValueError(f'unknown {label} schema fields')


def domain(value, values):
    if values == list(range(256)):
        return 'true'
    if values == list(range(len(values))) and len(values) > 1:
        return f'{value} < {len(values)}'
    if len(values) == 1:
        return f'{value} == {values[0]}'
    if values == list(range(values[0], values[-1] + 1)):
        return f'matches!({value}, {values[0]}..={values[-1]})'
    return f'matches!({value}, ' + ' | '.join(map(str, values)) + ')'


def view_names(view):
    names = dict(enumerate(view.get('names', [])))
    numbered = view.get('numbered')
    if numbered:
        for number in numbered['numbers']:
            if number in names:
                raise ValueError('overlapping named and numbered registers')
            names[number] = f'{numbered["prefix"]}{number}{numbered.get("suffix", "")}'
    return names


def validate(schema):
    known_keys(schema, 'classes decoder_only', 'register')
    variants, ids, tags, spellings, kinds, patterns = [set() for _ in range(6)]
    for row in schema['classes']:
        known_keys(row, 'variant id symbolic_tag views high_byte format isa_kinds decode doc aliases', 'register class')
        variant = row['variant']
        if not re.fullmatch('[A-Z][A-Za-z0-9]*', variant) or variant in variants:
            raise ValueError(f'invalid or duplicate register class: {variant}')
        variants.add(variant)
        for key, seen in [('id', ids), ('symbolic_tag', tags)]:
            value = row[key]
            if type(value) is not int or not 0 <= value <= 255 or value in seen:
                raise ValueError(f'invalid or duplicate register {key}: {value}')
            seen.add(value)
        widths, numbers = [], None
        for view in row['views']:
            known_keys(view, 'width names numbered', 'register view')
            width = view['width']
            if type(width) is not int or not 0 < width <= 65535 or width in widths:
                raise ValueError(f'invalid or duplicate register width: {width}')
            widths.append(width)
            if 'numbered' in view:
                pattern = view['numbered']
                known_keys(pattern, 'prefix suffix numbers parse_digits', 'numeric register')
                ns = pattern['numbers']
                if not ns or any(type(n) is not int or not 0 <= n <= 255 for n in ns) or ns != sorted(set(ns)):
                    raise ValueError('invalid register numbers')
                key = (pattern['prefix'], pattern.get('suffix', ''))
                if not key[0] or key in patterns:
                    raise ValueError('duplicate or empty numeric register pattern')
                patterns.add(key)
                digits = pattern.get('parse_digits')
                if digits is not None and (type(digits) is not int or not 1 <= digits <= 3):
                    raise ValueError('invalid numeric register length')
            names = view_names(view)
            if not names or any(not 0 <= n <= 255 for n in names) or numbers is not None and set(names) != numbers:
                raise ValueError('register views must share a nonempty number domain')
            numbers = set(names)
            for name in names.values():
                if not name or name != name.lower() or name in spellings:
                    raise ValueError(f'duplicate or invalid register spelling: {name}')
                spellings.add(name)
        if not widths:
            raise ValueError('register class needs a view')
        high = row.get('high_byte')
        if high:
            known_keys(high, 'first width names', 'high-byte register')
            ns = list(range(high['first'], high['first'] + len(high['names'])))
            if not high['names'] or high['width'] not in widths or not set(ns) <= numbers:
                raise ValueError('invalid high-byte register domain')
            for name in high['names']:
                if not name or name != name.lower() or name in spellings:
                    raise ValueError('duplicate high-byte register spelling')
                spellings.add(name)
        for alias in row.get('aliases', []):
            known_keys(alias, 'name number width', 'register alias')
            if not alias['name'] or alias['name'] != alias['name'].lower() or alias['width'] not in widths or alias['number'] not in numbers or alias['name'] in spellings:
                raise ValueError('invalid or duplicate register alias')
            spellings.add(alias['name'])
        fmt = row.get('format', {})
        known_keys(fmt, 'check fixed_width fallback_width fixed_number', 'register formatting')
        if len(fmt.get('check', DIMS)) != len(set(fmt.get('check', DIMS))) or set(fmt.get('check', DIMS)) - set(DIMS):
            raise ValueError('unknown or duplicate formatting check')
        for key in ['fixed_width', 'fallback_width']:
            if key in fmt and fmt[key] not in widths:
                raise ValueError('unknown formatting width')
        if 'fixed_width' in fmt and 'fallback_width' in fmt:
            raise ValueError('ambiguous formatting width')
        if 'fixed_number' in fmt and fmt['fixed_number'] not in numbers:
            raise ValueError('unknown formatting number')
        decode = row.get('decode')
        if decode:
            known_keys(decode, 'width check_number', 'decoder register')
        if decode and (decode['width'] not in widths or type(decode['check_number']) is not bool):
            raise ValueError('invalid decoder register view')
        for kind in row.get('isa_kinds', []):
            if kind in kinds:
                raise ValueError(f'duplicate ISA register kind: {kind}')
            kinds.add(kind)
    for row in schema.get('decoder_only', []):
        known_keys(row, 'isa_kind prefix suffix', 'decoder-only register')
        if row['isa_kind'] in kinds or not row['prefix']:
            raise ValueError('invalid or duplicate decoder-only register kind')
        kinds.add(row['isa_kind'])


def dimensions(row):
    numbers = sorted(view_names(row['views'][0]))
    widths = [v['width'] for v in row['views']]
    high = row.get('high_byte')
    return {
        'number': domain('self.number', numbers),
        'width': domain('self.width', widths),
        'high_byte': ('!self.high_byte || (' + domain('self.number', list(range(high['first'], high['first'] + len(high['names'])))) + f' && self.width == {high["width"]})') if high else '!self.high_byte',
    }


def definitions(schema):
    rows = schema['classes']
    lines = [HEADER, '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]', 'pub enum RegisterClass {']
    for row in rows:
        if row.get('doc'):
            lines.append('    /// ' + row['doc'])
        lines.append(f'    {row["variant"]} = {row["id"]},')
    lines += ['}', 'impl RegisterClass {',
              '    /// Stable Keel symbolic tag; separate from the enum discriminant.',
              '    pub const fn symbolic_tag(self) -> u8 {', '        match self {']
    lines += [f'            Self::{r["variant"]} => {r["symbolic_tag"]},' for r in rows]
    lines += ['        }', '    }',
              '    pub const fn from_symbolic_tag(tag: u8) -> Option<Self> {', '        Some(match tag {']
    lines += [f'            {r["symbolic_tag"]} => Self::{r["variant"]},' for r in rows]
    lines += ['            _ => return None,', '        })', '    }',
              '    /// Register class for a shared ISA operand kind.',
              '    pub fn from_isa_kind(kind: &str) -> Option<Self> {', '        Some(match kind {']
    for row in rows:
        if row.get('isa_kinds'):
            lines.append('            ' + ' | '.join(json.dumps(k) for k in row['isa_kinds']) + f' => Self::{row["variant"]},')
    lines += ['            _ => return None,', '        })', '    }', '}',
              '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]', 'pub struct Register {',
              '    pub class: RegisterClass,', '    pub number: u8,', '    pub width: u16,',
              '    pub high_byte: bool,', '}', 'impl Register {',
              '    pub fn parse(s: &str) -> Option<Self> {', '        let s = lowercase(s);',
              '        let s = s.as_ref();', '        let named = match s {']
    for row in rows:
        named = [(name, n, v['width'], False) for v in row['views'] for n, name in enumerate(v.get('names', []))]
        if row.get('high_byte'):
            high = row['high_byte']
            named += [(name, n + high['first'], high['width'], True) for n, name in enumerate(high['names'])]
        named += [(a['name'], a['number'], a['width'], False) for a in row.get('aliases', [])]
        for name, number, width, high in named:
            lines.append(f'            {json.dumps(name)} => Some((RegisterClass::{row["variant"]}, {number}, {width}, {str(high).lower()})),')
    lines += ['            _ => None,', '        };',
              '        if let Some((class, number, width, high_byte)) = named {',
              '            return Some(Self { class, number, width, high_byte });', '        }']
    for row in rows:
        for view in row['views']:
            p = view.get('numbered')
            if not p:
                continue
            lines += [f'        if let Some(rest) = s.strip_prefix({json.dumps(p["prefix"])})',
                      f'            && let Some(number) = rest.strip_suffix({json.dumps(p.get("suffix", ""))})']
            digits = p.get('parse_digits')
            if digits:
                lines += ['        {', f'            if number.len() != {digits} {{',
                          '                return None;', '            }',
                          '            if let Ok(number) = number.parse::<u8>()',
                          f'                && {domain("number", p["numbers"])}', '            {']
            else:
                lines += ['            && let Ok(number) = number.parse::<u8>()',
                          f'            && {domain("number", p["numbers"])}', '        {']
            lines += [f'                return Some(Self {{ class: RegisterClass::{row["variant"]}, number, width: {view["width"]}, high_byte: false }});']
            if digits:
                lines.append('            }')
            lines.append('        }')
    lines += ['        None', '    }',
              '    /// Structural validity, independent of instruction/address restrictions.',
              '    pub fn is_valid(self) -> bool {', '        match self.class {']
    for row in rows:
        lines.append(f'            RegisterClass::{row["variant"]} => ' + ' && '.join(f'({x})' for x in dimensions(row).values()) + ',')
    return '\n'.join(lines + ['        }', '    }', '}', ''])


def render_view(view, fmt, indent):
    prefix = ' ' * indent
    numbered = view.get('numbered')
    number = str(fmt['fixed_number']) if 'fixed_number' in fmt else 'self.number'
    if numbered and not view.get('names'):
        lines = [f'{prefix}w.write_str({json.dumps(numbered["prefix"])})?;']
        end = numbered.get('suffix', '')
        lines.append(f'{prefix}write_int(w, {number}.into(), false)' + ('?;' if end else ''))
        if end:
            lines.append(f'{prefix}w.write_str({json.dumps(end)})')
        return lines
    names = view_names(view)
    if 'fixed_number' in fmt:
        return [f'{prefix}w.write_str({json.dumps(names[fmt["fixed_number"]])})']
    return [f'{prefix}w.write_str(match self.number {{',
            *[f'{prefix}    {n} => {json.dumps(s)},' for n, s in names.items()],
            f'{prefix}    _ => return Err(fmt::Error),', f'{prefix}}})']


def formatting(schema):
    lines = [HEADER, 'impl Register {', '    fn write_to<W: Write + ?Sized>(&self, w: &mut W) -> fmt::Result {', '        match self.class {']
    for row in schema['classes']:
        lines.append(f'            RegisterClass::{row["variant"]} => {{')
        fmt = row.get('format', {})
        checks = fmt.get('check', DIMS)
        if checks:
            expr = (dimensions(row)[checks[0]] if len(checks) == 1 else
                    ' && '.join(f'({dimensions(row)[d]})' for d in checks))
            lines += [f'                if !({expr}) {{', '                    return Err(fmt::Error);', '                }']
        high = row.get('high_byte')
        if high:
            lines += ['                if self.high_byte {', '                    return w.write_str(match self.number {']
            lines += [f'                        {n + high["first"]} => {json.dumps(s)},' for n, s in enumerate(high['names'])]
            lines += ['                        _ => return Err(fmt::Error),', '                    });', '                }']
        views = row['views']
        fixed = fmt.get('fixed_width')
        if fixed is not None or len(views) == 1:
            view = next(v for v in views if v['width'] == fixed) if fixed else views[0]
            lines += render_view(view, fmt, 16)
        else:
            lines.append('                match self.width {')
            for view in views:
                lines.append(f'                    {view["width"]} => {{')
                lines += render_view(view, fmt, 24)
                lines.append('                    }')
            if 'fallback_width' in fmt:
                lines.append('                    _ => {')
                lines += render_view(next(v for v in views if v['width'] == fmt['fallback_width']), fmt, 24)
                lines.append('                    }')
            else:
                lines.append('                    _ => Err(fmt::Error),')
            lines.append('                }')
        lines.append('            }')
    return '\n'.join(lines + ['        }', '    }', '}', ''])


def decoder_names(schema):
    lines = [HEADER, '/// Names from decoded fields; this does not establish architectural validity.',
             '#[rustfmt::skip]',
             'pub fn register_name(kind: &str, number: u8) -> Option<String> {', '    Some(match kind {']
    for row in schema['classes']:
        decode = row.get('decode')
        if not decode:
            continue
        view = next(v for v in row['views'] if v['width'] == decode['width'])
        numbered = view.get('numbered')
        for kind in row['isa_kinds']:
            lines.append(f'        {json.dumps(kind)} => {{')
            if decode['check_number']:
                lines.append(f'            if !({domain("number", sorted(view_names(view)))}) {{ return None; }}')
            if numbered:
                lines.append('            format!(' + json.dumps(numbered['prefix'] + '{number}' + numbered.get('suffix', '')) + ')')
            else:
                lines += ['            match number {',
                          *[f'                {n} => {json.dumps(name)}.into(),' for n, name in view_names(view).items()],
                          '                _ => return None,', '            }']
            lines.append('        }')
    for row in schema.get('decoder_only', []):
        lines.append(f'        {json.dumps(row["isa_kind"])} => format!(' + json.dumps(row['prefix'] + '{number}' + row.get('suffix', '')) + '),')
    return '\n'.join(lines + ['        _ => return None,', '    })', '}', ''])


def outputs(root, output):
    schema = json.loads((root / 'registers.json').read_text())
    validate(schema)
    return {output.with_name('registers.rs'): definitions(schema),
            output.with_name('register_format.rs'): formatting(schema),
            output.with_name('register_names.rs'): decoder_names(schema)}

"""Generate reviewed x86 system declarations and regular lowering bindings."""
import json
import re

import system_lowering

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
TYPES = {'I8', 'I16', 'I32', 'I64', 'Ptr'}
MEMORY = {'None', 'Read', 'Write', 'ReadWrite', 'Barrier'}


def validate(schema):
    if not isinstance(schema, dict) or set(schema) != {'first_id', 'intrinsics'}:
        raise ValueError('unknown or missing system intrinsic schema fields')
    if type(schema['first_id']) is not int or schema['first_id'] != 774:
        raise ValueError('system intrinsic prefix must retain 774 IDs')
    rows = schema['intrinsics']
    if not isinstance(rows, list) or not rows:
        raise ValueError('system intrinsic inventory must not be empty')
    variants, names = set(), set()
    for offset, row in enumerate(rows):
        if not isinstance(row, dict) or set(row) != {'id', 'variant', 'name', 'params', 'returns', 'pure',
                        'memory', 'target', 'doc', 'lowering'}:
            raise ValueError('unknown or missing system intrinsic fields')
        if type(row['id']) is not int or row['id'] != schema['first_id'] + offset:
            raise ValueError('system intrinsic IDs must be contiguous and ordered')
        variant, name = row['variant'], row['name']
        if not isinstance(variant, str) or not re.fullmatch(r'X86[A-Za-z0-9]+', variant) or variant in variants:
            raise ValueError('invalid or duplicate system intrinsic variant')
        if not isinstance(name, str) or not re.fullmatch(r'x86_[a-z0-9_]+', name) or name in names:
            raise ValueError('invalid or duplicate system intrinsic name')
        variants.add(variant)
        names.add(name)
        for field in ('params', 'returns'):
            if not isinstance(row[field], list) or any(not isinstance(t, str) or t not in TYPES for t in row[field]):
                raise ValueError('unsupported system intrinsic type')
        if type(row['pure']) is not bool or not isinstance(row['memory'], str) or row['memory'] not in MEMORY:
            raise ValueError('invalid system intrinsic effects')
        if row['pure'] and row['memory'] != 'None':
            raise ValueError('pure system intrinsic cannot have memory effects')
        if row['target'] != 'x86_64':
            raise ValueError('unsupported system intrinsic target')
        if not isinstance(row['doc'], str) or not row['doc'].strip():
            raise ValueError('system intrinsic requires a contract description')
    system_lowering.validate(rows)
    return rows


def generate(schema):
    rows = validate(schema)
    lines = [HEADER, '// Semantic policy is reviewed in system-intrinsics.json, not inferred from ISA bytes.',
             'use super::{Intrinsic, IntrinsicInfo};', 'use crate::Type;', '',
             'macro_rules! define_intrinsics {', '    ($($prefix:tt)*) => {',
             '        #[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]',
             '        pub enum Intrinsic {', '            $($prefix)*']
    for row in rows:
        lines += [f'            #[doc = {json.dumps(row["doc"], ensure_ascii=False)}]',
                  f'            {row["variant"]} = {row["id"]},']
    lines += ['        }', '    };', '}', '',
              'macro_rules! define_intrinsic_inventory {', '    ($($prefix:path,)*) => {',
              f'        pub const ALL: [Intrinsic; {schema["first_id"] + len(rows)}] = [',
              '            $($prefix,)*']
    lines += [f'            Intrinsic::{row["variant"]},' for row in rows]
    lines += ['        ];', '    };', '}', '',
              '/// Generated patterns for exhaustive target and effect classifications.',
              '#[doc(hidden)]', '#[macro_export]', 'macro_rules! x86_system_intrinsics {']
    groups = {'all': rows, 'x86_64': rows}
    groups.update({effect: [r for r in rows if r['memory'] == effect] for effect in sorted(MEMORY)})
    for group, members in groups.items():
        if members:
            lines += [f'    ({group}) => {{']
            lines += [('        ' if i == 0 else '        | ') + '$crate::Intrinsic::' + r['variant']
                      for i, r in enumerate(members)]
            lines += ['    };']
    lines += ['}', '', 'impl Intrinsic {',
              '    pub(super) fn generated_system_info(self) -> Option<IntrinsicInfo> {',
              '        Some(match self {']
    for row in rows:
        ty = lambda values: '&[' + ', '.join(f'Type::{v}' for v in values) + ']'
        lines += [f'            Self::{row["variant"]} => IntrinsicInfo {{',
                  f'                name: "{row["name"]}",',
                  f'                params: {ty(row["params"])},',
                  f'                returns: {ty(row["returns"])},',
                  f'                pure: {str(row["pure"]).lower()},', '            },']
    lines += ['            _ => return None,', '        })', '    }', '',
              '    pub(crate) fn generated_system_memory_effects(self) -> crate::MemoryEffects {',
              '        match self {']
    for effect in sorted(MEMORY):
        if groups[effect]:
            lines += [f'            x86_system_intrinsics!({effect}) => crate::MemoryEffects::{effect},']
    lines += ['            _ => unreachable!("not a declared x86 system intrinsic"),',
              '        }', '    }', '']
    lines += system_lowering.ir_helpers(rows)
    lines += ['}', '']
    return '\n'.join(lines)


def outputs(root, output):
    schema = json.loads((root / 'system-intrinsics.json').read_text())
    target = root.parents[1] / 'crates/keel-ir/src/generated/x86_system_intrinsics.rs'
    return {target: generate(schema),
            root.parents[1] / 'crates/keel-codegen/src/x86_64/generated/system_lowering.rs':
                system_lowering.generate(validate(schema))}

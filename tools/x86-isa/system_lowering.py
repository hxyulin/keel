"""Validated regular lowering bindings; emission and architectural contracts stay explicit."""
import json
from functools import lru_cache
from pathlib import Path

HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
HOOKS = {'rdmsr': (['I32'], ['I64'], 'X86Rdmsr'),
         'wrmsr': (['I32', 'I64'], [], 'X86Wrmsr')}


@lru_cache(maxsize=1)
def policy():
    root = Path(__file__).resolve().parent
    adapters = json.loads((root / 'keel-adapters.json').read_text())
    core = json.loads((root / 'core-identities.json').read_text())
    registers = json.loads((root / 'registers.json').read_text())
    forms = json.loads((root / 'zydis.json').read_text())
    fixed = {r['mnemonic']: r['variant'] for r in adapters['identities']['fixed']}
    core = {r['mnemonic']: r['variant'] for r in core if 'mnemonic' in r}
    regs = {}
    for cls in registers['classes']:
        if cls['variant'] not in ('Control', 'Debug'):
            continue
        for view in cls['views']:
            numbered = view['numbered']
            for number in numbered['numbers']:
                name = numbered['prefix'] + str(number) + numbered['suffix']
                regs[name] = (cls['variant'], number, view['width'])
    return fixed, core, regs, forms


def fixed_opcode(name):
    fixed, _, _, forms = policy()
    if not isinstance(name, str) or name not in fixed or not any(
            r['mnemonic'] == name and r.get('encoding') is None
            and r.get('meta_info', {}).get('category') in ('SYSTEM', 'FLAGOP')
            and all(not o.get('visible', True) and o.get('operand_type') == 'implicit_reg'
                    and o.get('register') == 'gs' for o in r.get('operands', []))
            for r in forms):
        raise ValueError('lowering needs a reviewed zero-operand system/flags shape without GPR or stack operands')
    return f'Opcode::Fixed(FixedOpcode::{fixed[name]})'


def validate(rows):
    _, core, regs, forms = policy()
    for row in rows:
        recipe = row.get('lowering')
        if not isinstance(recipe, dict):
            raise ValueError('system intrinsic requires a lowering recipe')
        kind = recipe.get('kind')
        if kind == 'fixed':
            if set(recipe) != {'kind', 'mnemonic'}:
                raise ValueError('unknown or missing fixed recipe fields')
            fixed_opcode(recipe['mnemonic'])
            signature = ([], [])
        elif kind == 'system_register':
            if set(recipe) != {'kind', 'register', 'direction'}:
                raise ValueError('unknown or missing system register recipe fields')
            if not isinstance(recipe['register'], str) or recipe['register'] not in regs:
                raise ValueError('invalid system register recipe register')
            if recipe['direction'] not in ('read', 'write'):
                raise ValueError('invalid system register recipe direction')
            signature = ([], ['I64']) if recipe['direction'] == 'read' else (['I64'], [])
        elif kind == 'unary':
            if set(recipe) != {'kind', 'mnemonic', 'operand', 'bits', 'argument'}:
                raise ValueError('unknown or missing unary recipe fields')
            name, bits, operand = recipe['mnemonic'], recipe['bits'], recipe['operand']
            if not isinstance(name, str) or name not in core:
                raise ValueError('unary recipe needs a public Core opcode')
            if operand not in ('register', 'memory_read', 'address_only'):
                raise ValueError('invalid unary operand role')
            if type(bits) is not int or bits not in (8, 16, 32, 64, 80):
                raise ValueError('invalid unary operand width')
            if type(recipe['argument']) is not int or recipe['argument'] != 0:
                raise ValueError('unary argument must identify the sole input')
            def matches(form):
                visible = [o for o in form.get('operands', []) if o.get('visible', True)]
                if form['mnemonic'] != name or form.get('encoding') is not None or len(visible) != 1:
                    return False
                op = visible[0]
                if operand == 'register':
                    return op['operand_type'] == f'gpr{bits}'
                return op['operand_type'] == 'mem' and op.get('width64') == bits // 8
            if not any(matches(f) for f in forms):
                raise ValueError('unary recipe has no matching imported operand form')
            signature = ([f'I{bits}'] if operand == 'register' else ['Ptr'], [])
        elif kind == 'adjacent_fixed':
            if set(recipe) != {'kind', 'mnemonics'} or recipe['mnemonics'] != ['sti', 'hlt']:
                raise ValueError('only the reviewed adjacent STI;HLT pair is supported')
            for name in recipe['mnemonics']:
                fixed_opcode(name)
            signature = ([], [])
        elif kind == 'handwritten':
            if set(recipe) != {'kind', 'handler'} or not isinstance(recipe['handler'], str) or recipe['handler'] not in HOOKS:
                raise ValueError('unknown handwritten lowering hook')
            signature = HOOKS[recipe['handler']][:2]
        else:
            raise ValueError('unknown system lowering recipe')
        if (row['params'], row['returns']) != signature:
            raise ValueError('lowering recipe does not match intrinsic signature')


def ir_helpers(rows):
    lines = []
    for method, kind, shape in [('x86_system_register', 'system_register', "(&'static str, bool)"),
                                ('x86_system_write', 'unary', "(&'static str, u16, bool)")]:
        doc = ('Raw system register access: (register, write); caller owns privilege and state.'
               if kind == 'system_register' else
               'Single operand: (opcode, encoded bits, pointer); address-only is not a data read.')
        lines += [f'    /// {doc}', f'    pub fn {method}(self) -> Option<{shape}> {{',
                  '        Some(match self {']
        for row in rows:
            r = row['lowering']
            if r['kind'] != kind:
                continue
            if kind == 'system_register':
                value = f'("{r["register"]}", {str(r["direction"] == "write").lower()})'
            else:
                value = f'("{r["mnemonic"]}", {r["bits"]}, {str(r["operand"] != "register").lower()})'
            lines += [f'            Self::{row["variant"]} => {value},']
        lines += ['            _ => return None,', '        })', '    }', '']
    return lines


def generate(rows):
    validate(rows)
    _, core, regs, _ = policy()
    lines = [HEADER, 'use keel_asm_ir::x86::{CoreOpcode, FixedOpcode, RegisterClass};', '',
             '#[derive(Clone, Copy)]', 'enum SystemOperand { Register, MemoryRead, AddressOnly }', '',
             'enum SystemLowering {', '    Fixed(Opcode),',
             '    SystemRegister { register: Register, write: bool },',
             '    Unary { opcode: Opcode, bits: u16, operand: SystemOperand },',
             '    AdjacentFixed([Opcode; 2]),', '    HandwrittenMsr(Intrinsic),', '}', '',
             '#[rustfmt::skip]', 'fn recipe(id: Intrinsic) -> Option<SystemLowering> {',
             '    Some(match id {']
    for row in rows:
        r = row['lowering']; kind = r['kind']
        if kind == 'fixed':
            value = f'SystemLowering::Fixed({fixed_opcode(r["mnemonic"])})'
        elif kind == 'system_register':
            cls, number, width = regs[r['register']]
            register = f'Register {{ class: RegisterClass::{cls}, number: {number}, width: {width}, high_byte: false }}'
            value = f'SystemLowering::SystemRegister {{ register: {register}, write: {str(r["direction"] == "write").lower()} }}'
        elif kind == 'unary':
            operand = {'register': 'Register', 'memory_read': 'MemoryRead', 'address_only': 'AddressOnly'}[r['operand']]
            value = f'SystemLowering::Unary {{ opcode: Opcode::Core(CoreOpcode::{core[r["mnemonic"]]}), bits: {r["bits"]}, operand: SystemOperand::{operand} }}'
        elif kind == 'adjacent_fixed':
            value = 'SystemLowering::AdjacentFixed([' + ', '.join(fixed_opcode(n) for n in r['mnemonics']) + '])'
        else:
            value = 'SystemLowering::HandwrittenMsr(Intrinsic::' + HOOKS[r['handler']][2] + ')'
        lines += [f'        Intrinsic::{row["variant"]} => {value},']
    lines += ['        _ => return None,', '    })', '}', '']
    return '\n'.join(lines)

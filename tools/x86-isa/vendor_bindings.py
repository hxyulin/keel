CONTROL_ALLOWED_VALUES = {'gather_scale': [1, 2, 4, 8]}
CONTROLS = {'none', 'imm8', 'u64_count'} | VALUE_CONTROLS.keys()


def ir_type(ty, first=None):
    if not isinstance(ty, str):
        raise ValueError('unknown type')
    if ty == 'same_as_input':
        return ir_type(first)
    ty = ty.removeprefix('int_')
    if ty in SCALARS:
        return 'Type::' + SCALARS[ty]
    if ty not in VECTORS:
        raise ValueError(f'unknown type {ty}')
    # Signed/unsigned integer C vectors use the same typed IR shape.
    shape = re.sub('^u', 'i', ty)
    return f'Type::Vector(VectorType::{shape[0].upper() + shape[1:]})'


def references(root):
    schema = json.loads((root / 'vendor-references.json').read_text())
    if set(schema) != {'version', 'references'} or type(schema['version']) is not int or schema['version'] != 1 or not isinstance(schema['references'], dict) or not schema['references']:
        raise ValueError('invalid vendor reference schema')
    for reference in schema['references'].values():
        if not isinstance(reference, dict) or not isinstance(reference.get('project'), str) or not reference['project'] or not isinstance(reference.get('scope'), str) or not reference['scope'] or not re.fullmatch('[0-9a-f]{40}', reference.get('commit', '')):
            raise ValueError('invalid binding provenance')
        if 'headers' in reference:
            if set(reference) != {'project', 'repository', 'tag', 'commit', 'license', 'scope', 'headers'} or not all(reference.get(field) for field in ['repository', 'tag', 'license']) or not reference['headers']:
                raise ValueError('invalid header provenance')
            for header, checksum in reference['headers'].items():
                if not re.fullmatch('[a-zA-Z0-9_]+\.h', header) or not re.fullmatch('[0-9a-f]{64}', checksum):
                    raise ValueError('invalid header checksum')
        elif set(reference) != {'project', 'commit', 'path', 'sha256', 'scope'} or not reference['path'] or not re.fullmatch('[0-9a-f]{64}', reference['sha256']):
            raise ValueError('invalid source provenance')
    return schema['references']


def check_reference_headers(root, directory):
    for reference in references(root).values():
        for header, expected in reference.get('headers', {}).items():
            if hashlib.sha256((directory / header).read_bytes()).hexdigest() != expected:
                raise ValueError(f'vendor reference checksum mismatch: {header}')


def validate(schema, root):
    if set(schema) != {'version', 'reference_file', 'bindings'} or type(schema['version']) is not int or schema['version'] != 1 or schema['reference_file'] != 'vendor-references.json':
        raise ValueError('unknown vendor binding schema')
    source_references = references(root)
    registry = {r['variant']: r['id'] for r in json.loads((root / 'intrinsic-registry.json').read_text())['intrinsics']}
    fields = {r['field'] for r in json.loads((root / 'feature-fields.json').read_text())}
    seen = set()
    rows = schema['bindings']
    if not isinstance(rows, list) or not rows:
        raise ValueError('empty binding inventory')
    required = {'builtin', 'intrinsic', 'intrinsic_id', 'family', 'header', 'params', 'result', 'control', 'features', 'ownership', 'reference'}
    for row in rows:
        if set(row) != required:
            raise ValueError('unknown binding fields')
        name = row['builtin']
        if not isinstance(name, str) or not re.fullmatch('[a-zA-Z_][a-zA-Z0-9_]*', name) or name in seen:
            raise ValueError('invalid or duplicate builtin identity')
        seen.add(name)
        if row['intrinsic'] not in registry or type(row['intrinsic_id']) is not int or registry[row['intrinsic']] != row['intrinsic_id']:
            raise ValueError('binding intrinsic ID mismatch')
        if row['family'] not in FAMILIES or row['control'] not in CONTROLS:
            raise ValueError('unknown binding recipe or control')
        if row['ownership'] not in {'keel', 'vendor'} or (name.startswith('keel_') != (row['ownership'] == 'keel')):
            raise ValueError('builtin ownership mismatch')
        if not isinstance(row['header'], str) or not re.fullmatch('[a-zA-Z0-9_]+\.h', row['header']):
            raise ValueError('invalid binding header')
        if not isinstance(row['features'], list) or len(set(row['features'])) != len(row['features']) or not set(row['features']) <= fields:
            raise ValueError('unknown or duplicate binding features')
        params = row['params']
        if not isinstance(params, list) or (not params and row['family'] != 'value'):
            raise ValueError('invalid binding parameters')
        for ty in params:
            ir_type(ty)
        if row['result'] != 'void':
            ir_type(row['result'], params[0] if params else None)
        elif row['family'] != 'value':
            raise ValueError('void result requires a semantic value binding')
        if row['reference'] not in source_references:
            raise ValueError('unknown binding reference')
        reference = source_references[row['reference']]
        if 'headers' in reference and row['header'] not in reference['headers']:
            raise ValueError('binding header lacks a pinned reference')
        family, control = row['family'], row['control']
        if family == 'aes' and (params not in [['i64x2'], ['i64x2', 'i64x2'], ['i64x2', 'i32']] or row['result'] != 'i64x2' or control not in {'none', 'imm8'}):
            raise ValueError('invalid AES signature')
        if family == 'packed_shift' and (params[0] not in {'int_i16x8', 'int_i32x4', 'int_i64x2', 'int_i16x16', 'int_i32x8', 'int_i64x4'} or params[1:] != ['u64'] or row['result'] != 'same_as_input' or control not in {'imm8', 'u64_count'}):
            raise ValueError('invalid packed shift signature')
        if family == 'saturating' and (params[0] not in {'i8x16', 'u8x16', 'i16x8', 'u16x8'} or params != [params[0], params[0]] or row['result'] != params[0] or control != 'none'):
            raise ValueError('invalid saturation signature')
        if family == 'packed_conversion' and ((params, row['result']) not in [(['i32x4'], 'f32x4'), (['f32x4'], 'i32x4')] or control != 'none'):
            raise ValueError('invalid conversion signature')
        if family == 'value':
            expected = next((name for name, (intrinsics, *_) in VALUE_CONTROLS.items()
                             if row['intrinsic'] in intrinsics), 'none')
            if control != expected:
                raise ValueError('value control differs from semantic parser recipe')
            if control != 'none':
                index = VALUE_CONTROLS[control][1]
                if len(params) != index + 1 or params[index] != 'i32':
                    raise ValueError(f'value control requires a trailing i32 parameter at index {index}')
    return rows


def generate(schema, root):
    rows = validate(schema, root)
    lines = [HEADER, 'use keel_ir::{Intrinsic, VectorType};', '',
             '#[derive(Clone, Copy)]', 'pub(crate) struct ImmediateControl {',
             '    pub(crate) index: usize,', '    pub(crate) maximum: i64,', '    pub(crate) mask: i64,',
             "    pub(crate) allowed_values: &'static [i64],",
             "    pub(crate) diagnostic: &'static str,", '}', '',
             '#[derive(Clone, Copy)]', 'enum Binding {',
             '    Aes(Intrinsic),', '    PackedShift(Intrinsic, VectorType, bool),',
             '    Saturating(Intrinsic, bool, bool),', '    PackedConversion(Intrinsic),',
             "    Value(Intrinsic, Option<&'static ImmediateControl>),", '}', '', '#[rustfmt::skip]', 'fn lookup(base: &str) -> Option<Binding> {',
             '    Some(match base {']
    for row in rows:
        variant = 'Intrinsic::' + row['intrinsic']
        if row['family'] == 'aes':
            value = f'Binding::Aes({variant})'
        elif row['family'] == 'packed_shift':
            shape = row['params'][0].removeprefix('int_')
            shape = shape[0].upper() + shape[1:]
            value = f'Binding::PackedShift({variant}, VectorType::{shape}, {str(row["control"] == "imm8").lower()})'
        elif row['family'] == 'saturating':
            ty = row['params'][0]
            value = f'Binding::Saturating({variant}, {str(ty.startswith("u")).lower()}, {str("16x" in ty).lower()})'
        elif row['family'] == 'packed_conversion':
            value = f'Binding::PackedConversion({variant})'
        else:
            control = 'None'
            if row['control'] != 'none':
                _, index, maximum, mask, diagnostic = VALUE_CONTROLS[row['control']]
                allowed = CONTROL_ALLOWED_VALUES.get(row['control'], [])
                control = f'Some(&ImmediateControl {{ allowed_values: &{allowed}, index: {index}, maximum: {maximum}, mask: {mask}, diagnostic: {json.dumps(diagnostic)} }})'
            value = f'Binding::Value({variant}, {control})'
        lines.append(f'        {json.dumps(row["builtin"])} => {value},')
    lines += ['        _ => return None,', '    })', '}', '',
              'pub(crate) fn recognized(base: &str) -> bool {', '    lookup(base).is_some()', '}', '']
    for name, variant, ty, value in [
        ('aes_builtin', 'Aes(id)', 'Intrinsic', 'id'),
        ('packed_shift_builtin', 'PackedShift(id, shape, immediate)', '(Intrinsic, VectorType, bool)', '(id, shape, immediate)'),
        ('saturating_builtin', 'Saturating(id, unsigned, word)', '(Intrinsic, bool, bool)', '(id, unsigned, word)'),
        ('packed_conversion_builtin', 'PackedConversion(id)', 'Intrinsic', 'id'),
        ('semantic_builtin', 'Value(id, control)', "(Intrinsic, Option<&'static ImmediateControl>)", '(id, control)'),
    ]:
        signature = f'pub(crate) fn {name}(base: &str) -> Option<{ty}> {{'
        if len(signature) > 100:
            lines += [f'pub(crate) fn {name}(', '    base: &str,', f') -> Option<{ty}> {{']
        else:
            lines.append(signature)
        lines += ['    match lookup(base)? {', f'        Binding::{variant} => Some({value}),',
                  '        _ => None,', '    }', '}', '']
    # Non-test const checks retain stable registry IDs without assigning new ones.
    lines += ['#[rustfmt::skip]', 'const _: () = {']
    for variant, identity in dict((row['intrinsic'], row['intrinsic_id']) for row in rows).items():
        lines.append(f'    assert!(Intrinsic::{variant} as u16 == {identity});')
    lines += ['};', '']
    lines += ['#[cfg(test)]', 'mod tests {', '    use super::*;', '    use keel_ir::Type;',
              '    #[test]', '    fn reviewed_signatures_match_semantic_intrinsics() {', '        #[rustfmt::skip]', '        let signatures: &[(Intrinsic, &[Type], &[Type])] = &[']
    for row in rows:
        params = ', '.join(ir_type(t) for t in row['params'])
        result = '' if row['result'] == 'void' else ir_type(row['result'], row['params'][0] if row['params'] else None)
        lines.append(f'            (Intrinsic::{row["intrinsic"]}, &[{params}], &[{result}]),')
    lines += ['        ];', '        for &(intrinsic, params, result) in signatures {',
              '            assert_eq!(intrinsic.info().params, params, "{intrinsic:?}");',
              '            assert_eq!(intrinsic.info().returns, result, "{intrinsic:?}");',
              '        }', '    }', '}']
    lines += ['']
    return '\n'.join(lines)


def outputs(root):
    schema = json.loads((root / 'vendor-bindings.json').read_text())
    return {root.parents[1] / 'crates/keel-c/src/generated/x86_builtins.rs': generate(schema, root)}

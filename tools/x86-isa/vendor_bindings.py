HEADER = '// Generated by tools/x86-isa/generate.py; do not edit.'
FAMILIES = {'aes', 'packed_shift', 'saturating', 'packed_conversion', 'value'}
SCALARS = {'i8': 'I8', 'i16': 'I16', 'ptr': 'Ptr', 'i64': 'I64', 'i32': 'I32', 'u64': 'I64', 'f32': 'F32', 'f64': 'F64'}
